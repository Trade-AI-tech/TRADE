/**
 * Equal-Weight Vote + Shrinkage — เลิกตั้งน้ำหนักเอง แล้วหดคะแนนเข้าหาศูนย์
 *
 * ─────────────────────────────── แนวคิดที่มา ───────────────────────────────
 *
 * ระบบให้คะแนนที่เขียนด้วยมือมักหน้าตาแบบ "MACD ตัดขึ้น +2, RSI>50 +1, ราคาเหนือ MA +2"
 * ตัวเลข 1/2/3 พวกนั้นไม่ได้มาจากการวัดอะไรเลย มันมาจากความรู้สึกว่าอันไหนสำคัญกว่า
 * และเพราะไม่ได้มาจากข้อมูล มันจึงเป็นพารามิเตอร์ที่ overfit ได้ฟรี ๆ โดยไม่มีใครตรวจ
 *
 * งานวิจัยด้านการรวมพยากรณ์ (forecast combination) ชี้ไปทางเดียวกันมานานว่า
 * ค่าเฉลี่ยน้ำหนักเท่ากันมักชนะน้ำหนักที่ประมาณค่ามาเอง เมื่อสัญญาณมีสัญญาณรบกวนสูง
 * — ที่เรียกกันว่า "forecast combination puzzle" กฎนี้จึงตัดน้ำหนักทิ้งทั้งหมด
 * ให้ทุกเงื่อนไขมีหนึ่งเสียงเท่ากันหมด แล้วเติมสองอย่างที่การโหวตเปล่า ๆ ไม่มี:
 *
 *   1. shrinkage — คะแนน = net / (nAvail + shrinkK) แทนที่จะเป็น net / nAvail
 *      ตัว shrinkK ที่บวกในตัวหารทำหน้าที่เหมือน "เสียงงดออกเสียงสมมติ shrinkK เสียง"
 *      ที่โหวตศูนย์เสมอ ผลคือคะแนนถูกดึงเข้าหาศูนย์ตลอด และถูกดึงแรงขึ้นเมื่อ
 *      เงื่อนไขที่ใช้ได้จริงมีน้อย ซึ่งตรงกับสัญชาตญาณว่า "หลักฐานน้อย = อย่ามั่นใจมาก"
 *      (รูปแบบเดียวกับ Laplace smoothing / posterior mean ของ Beta prior)
 *   2. NaN ไม่ใช่ศูนย์ แต่คือ "ไม่ได้มาลงคะแนน" — เงื่อนไขที่คำนวณไม่ได้จะลด nAvail
 *      ทำให้ตัวหารเล็กลงก็จริง แต่ก็ทำให้ net ที่ทำได้สูงสุดเล็กลงด้วย และถ้าต่ำกว่า
 *      minAvailable กฎจะไม่ออกความเห็นเลย
 *
 * ─────────────────────────────── ทำไมเกณฑ์เป็นแบบนี้ ───────────────────────────────
 *
 * · shrinkK = 3 เทียบกับ 8 เงื่อนไข — เมื่อครบทุกเสียงตัวหารเป็น 11 คะแนนเต็มจึงได้
 *   แค่ 8/11 ≈ 0.727 ไม่ใช่ 1 ซึ่งเป็นเจตนา: กฎนี้ไม่ควรพูดคำว่า "แน่ใจเต็มร้อย" ได้เลย
 * · threshold = 0.45 — ที่ nAvail = 8 แปลว่าต้องมี net ≥ 5 (เช่น 6 เสียงต่อ 1 เสียง)
 *   ถ้าเงื่อนไขใช้ได้แค่ 5 ข้อ ต้องเกือบเอกฉันท์ (net ≥ 4 จาก 5) ถึงจะผ่านเส้นเดียวกัน
 *   — เส้นเดียว เกณฑ์ขยับเอง นั่นคือสิ่งที่ shrinkage ทำให้
 *
 * ─────────────────────────────── ข้อจำกัดที่รู้ตัว ───────────────────────────────
 *
 * 1. "น้ำหนักเท่ากัน" แก้ปัญหาน้ำหนักมั่ว แต่ไม่ได้แก้ปัญหาเงื่อนไขซ้ำซ้อน — เงื่อนไข 8 ข้อนี้
 *    หลายข้ออ่านราคาเดียวกัน (close vs ma50 กับ close vs bb.middle แทบเป็นเรื่องเดียวกัน
 *    เพราะ bb.middle คือ SMA20) ดังนั้น "8 เสียง" จริง ๆ แล้วมีข้อมูลอิสระน้อยกว่า 8 มาก
 *    กฎ family-quorum ในโฟลเดอร์เดียวกันตั้งใจแก้จุดนี้ ส่วนกฎนี้จงใจไม่แก้ เพื่อให้เทียบกันได้
 * 2. shrinkK ก็ยังเป็นตัวเลขที่ตั้งเอง — เราแค่ย้ายที่ของ "ตัวเลขที่ตั้งเอง" จาก 8 ตัว
 *    (น้ำหนักรายเงื่อนไข) มาเหลือ 2 ตัว (shrinkK, threshold) พื้นที่ overfit เล็กลง ไม่ใช่หายไป
 * 3. เป็นกฎแบบสถานะ ออกสัญญาณทุกแท่งที่คะแนนยังผ่านเส้น ไม้จึงซ้อนทับกันหนัก
 *    จำนวนไม้ในรายงานไม่ใช่จำนวนโอกาสอิสระ
 * 4. volumeRatio ไม่ได้ถูกใช้เลยทั้งที่ตัวรันมีให้ เพราะแคชของคู่เงิน FOREX มี volume = 0
 *    ทั้งชุด (Yahoo ไม่ให้ปริมาณของ spot FX) เงื่อนไขที่อิง volume จะ NaN ใน 11 จาก 13 ตัว
 */

export const meta = {
  id: 'confluence-core-equal-weight-vote',
  name: 'โหวตน้ำหนักเท่ากัน 8 เงื่อนไข แล้วหดเข้าหาศูนย์',
  family: 'confluence',
  needsHtf: false,
  params: {
    /** จำนวนเงื่อนไขทั้งหมดที่มีสิทธิ์ลงคะแนน */
    conditionCount: 8,
    /** "เสียงงดออกเสียงสมมติ" ที่บวกในตัวหาร — ยิ่งมาก ยิ่งหดเข้าหาศูนย์แรง */
    shrinkK: 3,
    /** ต้องมีเงื่อนไขที่คำนวณได้อย่างน้อยเท่านี้ ไม่งั้นไม่ออกความเห็น */
    minAvailable: 5,
    /** |คะแนนหลังหด| ต้องถึงเส้นนี้จึงนับเป็นสัญญาณ */
    threshold: 0.45,
    /** เส้นกลางของ RSI */
    rsiMid: 50,
    /** เงื่อนไขโมเมนตัมราคาดิบ: เทียบ close กับกี่แท่งก่อนหน้า */
    momentumLookback: 10,
  },
};

/** +1 ถ้า a > b · −1 ถ้า a < b · 0 ถ้าเท่ากันพอดี · null = คำนวณไม่ได้ (ไม่นับเป็นผู้มีสิทธิ์) */
function cmp(a, b) {
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  if (a > b) return 1;
  if (a < b) return -1;
  return 0;
}

export function evaluate(ctx) {
  const p = meta.params;
  const { bars, t, ind } = ctx;
  const close = bars[t].close;

  const prevIdx = t - p.momentumLookback;
  const closePrev = prevIdx >= 0 ? bars[prevIdx].close : NaN;

  // ทุกเงื่อนไขมีหนึ่งเสียงเท่ากันหมด ไม่มีตัวไหนได้ 2 คะแนน — นั่นคือทั้งหมดของกฎนี้
  const votes = [
    cmp(close, ind.ma50[t]),                              // 1. ราคาเทียบเส้น 50
    cmp(ind.ma50[t], ind.ma200[t]),                       // 2. เส้นเร็วเทียบเส้นช้า
    cmp(ind.macd.macdLine[t], ind.macd.signalLine[t]),    // 3. MACD เทียบเส้นสัญญาณ
    cmp(ind.macd.histogram[t], 0),                        // 4. ทิศของ histogram
    cmp(ind.rsi[t], p.rsiMid),                            // 5. RSI เทียบเส้นกลาง
    cmp(ind.stoch.k[t], ind.stoch.d[t]),                  // 6. %K เทียบ %D
    cmp(close, ind.bb.middle[t]),                         // 7. ราคาเทียบกลางกรอบ
    cmp(close, closePrev),                                // 8. โมเมนตัมราคาดิบ
  ];

  let net = 0;
  let nAvail = 0;
  for (const v of votes) {
    if (v === null) continue; // NaN = ไม่มาลงคะแนน ไม่ใช่โหวตศูนย์
    nAvail++;
    net += v;
  }

  if (nAvail < p.minAvailable) return { bull: false, bear: false, veto: null, score: 0 };

  // หัวใจของกฎ: ตัวหารเป็น nAvail + shrinkK ไม่ใช่ nAvail
  const shrunk = net / (nAvail + p.shrinkK);

  const bull = shrunk >= p.threshold;
  const bear = shrunk <= -p.threshold;

  // ปรับสเกลด้วยค่าที่ "เป็นไปได้สูงสุด" (เสียงครบทุกข้อและเอกฉันท์) เพื่อให้ score เต็ม 1 ได้จริง
  const fullScale = p.conditionCount / (p.conditionCount + p.shrinkK);
  const score = bull || bear ? Math.min(1, Math.abs(shrunk) / fullScale) : 0;

  return { bull, bear, veto: null, score };
}
