/**
 * Multi-Timeframe Confluence Counter — นับ "จำนวนเงื่อนไขที่ตรงกัน" แทนการรวมคะแนน
 *
 * ─────────────────────────────── แนวคิดที่มา ───────────────────────────────
 *
 * ระบบ MTF ส่วนใหญ่รวมคะแนนสองกรอบเวลาด้วยสูตรแบบ score = 0.6×HTF + 0.4×LTF
 * ซึ่งมีรูรั่วที่มองไม่เห็นจนกว่าจะเจอตัวอย่างจริง: คะแนนสูงมาก ๆ ของกรอบเดียว
 * ชดเชยคะแนนติดลบของอีกกรอบได้ ผลคือได้สัญญาณ "แข็งแรง" ที่ในความจริงแล้วคือ
 * กรอบใหญ่กับกรอบเล็กกำลังเถียงกันอยู่ แค่ฝั่งหนึ่งเสียงดังกว่า
 *
 * การนับหัวแก้ปัญหานี้ตรง ๆ เพราะเงื่อนไขหนึ่งข้อนับได้แค่หนึ่ง ไม่ว่ามันจะ "แรง" แค่ไหน
 * ไม่มีอะไรชดเชยอะไรได้ และเราสั่งเพิ่มได้ตรง ๆ ว่าต้องมีกี่ข้อ จากฝั่งไหนบ้าง:
 *   · ทั้งหมดต้องตรงกันอย่างน้อย minMatched ข้อ จาก 7 ข้อ
 *   · ฝั่งตรงข้ามมีได้ไม่เกิน maxOpposed ข้อ
 *   · และในจำนวนนั้นต้องมาจากกรอบใหญ่อย่างน้อย minHtfMatched ข้อ  ← ข้อนี้คือหัวใจ
 * เงื่อนไขข้อสุดท้ายทำให้ "กรอบเล็กครบทุกข้อแต่กรอบใหญ่ไม่เห็นด้วยเลย" ผ่านไม่ได้
 * ซึ่งเป็นกรณีที่สูตรถ่วงน้ำหนักปล่อยผ่านเสมอ
 *
 * ─────────────────────────────── เรื่องเวลาที่ต้องระวัง ───────────────────────────────
 *
 * ctx.htf ที่ตัวรันส่งมาเป็นแท่ง 1D ที่ "ปิดครบวันแล้ว" ก่อนเวลาแท่ง 1H ปัจจุบันเท่านั้น
 * กฎนี้จึงอ่าน htf.ind ที่ htf.t ได้ตรง ๆ โดยไม่ต้องเลื่อนดัชนีเอง และห้ามอ่าน htf.t + 1
 * เด็ดขาด เพราะนั่นคือวันที่ยังไม่ปิด ณ เวลาที่เราตัดสินใจ
 *
 * ─────────────────────────────── ข้อจำกัดที่รู้ตัว ───────────────────────────────
 *
 * 1. needsHtf = true แปลว่าบนกรอบ 1D กฎนี้ "ไม่มีวันออกสัญญาณ" เพราะตัวรันให้ ctx.htf
 *    เป็น null เมื่อกรอบปัจจุบันคือ 1D — แถว 1D ที่ได้ 0 ไม้จึงเป็นผลจากโครงสร้าง
 *    ไม่ใช่เพราะเกณฑ์แน่นเกินไป อย่าอ่านตัวเลขนั้นว่ากฎแย่
 * 2. บริบท 1D ที่กฎนี้เห็นตอนวัดบน 1H เป็นแท่งที่อยู่ในช่วง test ของ 1D (1H ย้อนได้แค่
 *    ~730 วัน จึงเลี่ยงไม่ได้) — ไม่ใช่การมองอนาคตของไม้ 1H แต่ห้ามเอาผลนี้ไปอ้างว่า
 *    ชุด test ของ 1D ยังบริสุทธิ์ ดูคำเตือนเดียวกันที่ตัวรันพิมพ์ออกมา
 * 3. การนับหัวโยนข้อมูลเรื่องขนาดทิ้งทั้งหมด — "ma50 เหนือ ma200 อยู่ 0.01%" กับ
 *    "เหนืออยู่ 8%" นับเท่ากันหมด กฎนี้จึงไวต่อกรณีที่สองเส้นเกือบทับกันเป็นพิเศษ
 * 4. เงื่อนไขทั้ง 7 ยังอ่านราคาปิดชุดเดียวกัน การนับได้ 6 จาก 7 ไม่ได้แปลว่ามีหลักฐาน
 *    อิสระหกชิ้น — แค่แปลว่าไม่มีมุมไหนที่เราดูแล้วเห็นตรงข้าม
 */

export const meta = {
  id: 'confluence-core-mtf-counter',
  name: 'ตัวนับ MTF: นับเงื่อนไขที่ตรงกันสองกรอบเวลา ไม่รวมคะแนน',
  family: 'mtf',
  needsHtf: true,
  params: {
    /** จำนวนเงื่อนไขทั้งหมด (LTF 4 + HTF 3) */
    totalConditions: 7,
    /** เงื่อนไขในกรอบใหญ่มีทั้งหมดกี่ข้อ */
    htfConditions: 3,
    /** ต้องตรงกันอย่างน้อยกี่ข้อ (นับรวมสองกรอบ) */
    minMatched: 5,
    /** ฝั่งตรงข้ามมีได้ไม่เกินกี่ข้อ */
    maxOpposed: 1,
    /** ในจำนวนที่ตรงกัน ต้องมาจากกรอบใหญ่อย่างน้อยกี่ข้อ */
    minHtfMatched: 2,
    /** เส้นกลางของ RSI */
    rsiMid: 50,
  },
};

/** +1 / −1 / 0 — 0 ครอบคลุมทั้ง "เท่ากันพอดี" และ "คำนวณไม่ได้" เพราะทั้งคู่ไม่ควรถูกนับ */
function side(a, b) {
  if (!Number.isFinite(a) || !Number.isFinite(b)) return 0;
  if (a > b) return 1;
  if (a < b) return -1;
  return 0;
}

export function evaluate(ctx) {
  const p = meta.params;
  const { bars, t, ind, htf } = ctx;

  // ไม่มีบริบทกรอบใหญ่ = ไม่มีสิทธิ์ตัดสินใจ (เกิดบน 1D เสมอ ตามที่หมายเหตุไว้ข้างบน)
  if (!htf) return { bull: false, bear: false, veto: null, score: 0 };

  const close = bars[t].close;
  const ltf = [
    side(close, ind.ma50[t]),
    side(ind.macd.macdLine[t], ind.macd.signalLine[t]),
    side(ind.rsi[t], p.rsiMid),
    side(ind.stoch.k[t], ind.stoch.d[t]),
  ];

  const h = htf.t;
  const htfClose = htf.bars[h].close;
  const big = [
    side(htfClose, htf.ind.ma50[h]),
    side(htf.ind.ma50[h], htf.ind.ma200[h]),
    side(htf.ind.macd.histogram[h], 0),
  ];

  let up = 0;
  let down = 0;
  for (const v of ltf.concat(big)) {
    if (v > 0) up++;
    else if (v < 0) down++;
  }

  let htfUp = 0;
  let htfDown = 0;
  for (const v of big) {
    if (v > 0) htfUp++;
    else if (v < 0) htfDown++;
  }

  const bull = up >= p.minMatched && down <= p.maxOpposed && htfUp >= p.minHtfMatched;
  const bear = down >= p.minMatched && up <= p.maxOpposed && htfDown >= p.minHtfMatched;

  const score = bull || bear
    ? Math.max(0, Math.min(1, Math.abs(up - down) / p.totalConditions))
    : 0;

  return { bull: bull && !bear, bear: bear && !bull, veto: null, score };
}
