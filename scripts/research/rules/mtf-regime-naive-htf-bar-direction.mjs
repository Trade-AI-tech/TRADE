/**
 * กฎ: ทิศของแท่ง HTF ล่าสุดแบบดิบ ๆ (Naive HTF Bar Direction)
 *
 * ─────────────────────────────── แนวคิดที่มา ───────────────────────────────
 *
 * นี่คือ "ตัวควบคุมหยาบที่สุด" ของตระกูล mtf ทั้งกอง — แท่งใหญ่ล่าสุดปิดเขียวก็ซื้อ
 * ปิดแดงก็ขาย ไม่มีตัวกรอง ไม่มีจังหวะ ไม่มีเงื่อนไขอะไรเลย มันไม่ได้มีไว้ให้ใช้จริง
 * แต่มีไว้ตอบคำถามที่กฎ mtf ทุกข้อต้องตอบให้ได้ก่อน: "ความซับซ้อนที่คุณใส่เพิ่มเข้าไป
 * ชนะการดูแค่สีของแท่งวันล่าสุดได้จริงไหม" ถ้ากฎ mtf ที่ประณีตกว่าทำได้ไม่ต่างจากไฟล์นี้
 * แปลว่าสิ่งที่มันวัดได้จริง ๆ มีแค่ "โมเมนตัมวันก่อนหน้า" ส่วนที่เหลือเป็นของประดับ
 *
 * ต้องเป็น baseline ที่ "ออกไม้แทบทุกแท่ง" ด้วย เพราะมันทำหน้าที่เป็นตัวประมาณ
 * ผลตอบแทนของการเดินไม้แบบสุ่มทิศตามโมเมนตัมบนกติกา SL/TP ชุดนี้ไปในตัว —
 * เลข avg R ของมันคือเส้นศูนย์ที่กฎอื่นต้องยืนให้เหนือกว่า
 *
 * ─────────────────────────── ทำไมตั้งเกณฑ์แบบนี้ ───────────────────────────
 *
 * · อ่าน htf.bars[htf.t] ตัวเดียว ซึ่งตัวรันการันตีแล้วว่าเป็นแท่งใหญ่ที่ปิดไปก่อน
 *   เวลาของ bars[t] จริง ๆ (เงื่อนไข ts_day + 1 วัน <= ts_hour) จึงไม่มีทางมองอนาคต
 * · minBodyAtrFrac ตั้งไว้ที่ 0 โดยตั้งใจ = ขอแค่ตัวแท่งไม่เป็นศูนย์ ห้ามใส่ตัวกรองความแรง
 *   เข้าไปเพราะจะไม่ใช่ baseline ที่หยาบที่สุดอีกต่อไป (แต่ประกาศเป็นพารามิเตอร์ไว้
 *   เผื่อวันหนึ่งอยากรู้ว่าการกรองแท่งเล็กทิ้งช่วยหรือไม่ช่วย จะได้ขยับค่าเดียวจบ)
 * · ต้องมี ATR(HTF) ที่ใช้ได้ถึงจะออกสัญญาณ ทั้งที่เงื่อนไขทิศไม่ได้ใช้ ATR เลย — เพราะ
 *   score ใช้ ATR เป็นตัวหาร ถ้าปล่อยให้ ATR เป็น NaN แล้วยังออกไม้ score จะเพี้ยน
 *   ผลข้างเคียงคือแท่งช่วงต้นชุด (ATR ยังคำนวณไม่ได้) จะไม่ออกสัญญาณ ซึ่งรับได้
 *
 * ─────────────────────────── ข้อจำกัดที่รู้ตัว ───────────────────────────
 *
 * 1. กฎนี้ไม่มีแนวคิดเรื่อง "จังหวะ" เลย ในกรอบ 1H มันจะออกสัญญาณทิศเดียวกันซ้ำ ๆ
 *    ทุกแท่งตลอดทั้งวันจนกว่าแท่งวันใหม่จะปิด ไม้ที่ได้จึงทับซ้อนกันหนักมาก
 *    จำนวนไม้ที่เห็นในรายงานไม่ใช่จำนวนเหตุการณ์อิสระ — ให้ดู CI แบบ cluster เป็นหลัก
 *    และอย่าเอา "ไม้เยอะ" ของกฎนี้ไปตีความว่าหลักฐานแน่นกว่ากฎที่ออกไม้น้อย
 * 2. บนกรอบ 1D จะได้ 0 ไม้ เพราะแคชไม่มี TF ที่ใหญ่กว่า 1D ให้เป็น htf (needsHtf = true)
 *    — เป็นข้อจำกัดเชิงโครงสร้าง ไม่ใช่เกณฑ์แน่นเกินไป
 * 3. สีของแท่งวันไม่ได้แยกระหว่าง "วันที่วิ่งขึ้นทั้งวัน" กับ "วันที่ดิ่งลงแล้วเด้งปิดบวกนิดเดียว"
 *    ซึ่งเป็นสองสถานการณ์ที่ต่างกันมาก กฎนี้จงใจไม่แยก เพราะการแยกคือหน้าที่ของกฎที่ดีกว่า
 * 4. ต้นทุนต่อไม้คงที่แต่จำนวนไม้มหาศาล ทำให้ผลรวม R ของกฎนี้ไวต่อค่าประมาณ COST_BPS
 *    มากกว่ากฎที่ออกไม้น้อย ถ้าค่าประมาณต้นทุนผิดทาง ผลของกฎนี้จะเลื่อนมากที่สุดในกอง
 */

export const meta = {
  id: 'mtf-regime-naive-htf-bar-direction',
  name: 'baseline หยาบ: แท่ง HTF ล่าสุดเขียวซื้อ / แดงขาย',
  family: 'mtf',
  needsHtf: true,
  params: {
    /** ตัวแท่ง HTF ต้องใหญ่กว่ากี่เท่าของ ATR(HTF) — 0 = ขอแค่ไม่เป็นศูนย์ (ตั้งใจให้หยาบ) */
    minBodyAtrFrac: 0,
    /** ตัวแท่งใหญ่เท่ากับ scoreAtrMult × ATR(HTF) ให้ถือว่า score เต็ม 1 */
    scoreAtrMult: 1.0,
  },
};

const NONE = Object.freeze({ bull: false, bear: false, veto: null, score: 0 });

const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);

/**
 * @param {{bars: Array, t: number, ind: object, htf: object|null}} ctx
 * @returns {{bull: boolean, bear: boolean, veto: null, score: number}}
 */
export function evaluate(ctx) {
  const { minBodyAtrFrac, scoreAtrMult } = meta.params;
  const { htf } = ctx;

  if (!htf) return { ...NONE };

  const j = htf.t;
  if (!Number.isInteger(j) || j < 0) return { ...NONE };

  const b = htf.bars[j];
  if (!b || !Number.isFinite(b.open) || !Number.isFinite(b.close)) return { ...NONE };

  const htfAtr = htf.ind.atr[j];
  if (!Number.isFinite(htfAtr) || !(htfAtr > 0)) return { ...NONE };

  const body = b.close - b.open;
  if (!Number.isFinite(body)) return { ...NONE };

  const minBody = minBodyAtrFrac * htfAtr;
  const bull = body > minBody;
  const bear = -body > minBody;

  const span = scoreAtrMult * htfAtr;
  const score = span > 0 ? clamp01(Math.abs(body) / span) : 0;

  return { bull, bear, veto: null, score: bull || bear ? score : 0 };
}
