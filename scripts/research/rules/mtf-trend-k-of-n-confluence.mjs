/**
 * k-of-N Confluence Count — นับว่ามี "ช่วงเวลา" กี่ช่วงที่เห็นตรงกัน แล้วเข้าเมื่อครบ k
 *
 * ─────────────────────────────── มาจากแนวคิดอะไร ───────────────────────────────
 *
 * แนวคิด confluence บอกว่าสัญญาณเดี่ยวเชื่อไม่ได้ แต่สัญญาณหลายตัวที่ "อิสระพอสมควร"
 * แล้วชี้ทางเดียวกันน่าเชื่อกว่า วิธีทำให้วัดได้คือเปลี่ยนจาก "ต้องผ่านทุกข้อ" (AND ยาว ๆ
 * ที่ยิ่งเพิ่มเงื่อนไขยิ่งไม่มีสัญญาณเหลือ) มาเป็น "ผ่านกี่ข้อจากทั้งหมด" ซึ่งยืดหยุ่นกว่า
 * และเปิดให้จูนความเข้มด้วยตัวเลขตัวเดียว (k) แทนการเลือกว่าจะตัดเงื่อนไขไหนทิ้ง
 *
 * ที่นี่ "ช่วงเวลา" หมายถึงช่วงมองย้อนหลังหลายขนาดบนอนุกรมเดียวกัน (5·10·20·60·120 แท่ง)
 * ไม่ใช่การรีแซมเปิลเป็น TF ใหม่ — เพราะแคชมีแค่ 1D กับ 1H และห้ามดึงข้อมูลเพิ่ม
 * การเทียบ close[t] กับ close[t−h] ที่ h ต่างกันคือการถามว่า "ถ้ามองด้วยสายตาของคนที่ถือ
 * h แท่ง เขากำไรหรือขาดทุน" ซึ่งเป็นนิยามของทิศเทรนด์ในสเกลนั้นแบบตรงไปตรงมาที่สุด
 *
 * ─────────────────────────────── ทำไมตั้งเกณฑ์แบบนี้ ───────────────────────────────
 *
 * · แต่ละช่วงลงคะแนน +1/−1 ก็ต่อเมื่อระยะทางถึง voteMinAtr เท่าของ ATR ปัจจุบัน
 *   ถ้าไม่ถึงถือว่า "งดออกเสียง" (0) — เพราะ close[t] มากกว่า close[t−5] อยู่เศษทศนิยม
 *   ไม่ใช่หลักฐานของอะไรเลย แต่ในการนับดิบ ๆ มันมีน้ำหนักเท่ากับการวิ่งสามเท่าตัว
 * · k=4 จาก N=5 เลือกให้ k มากกว่า N/2 เพื่อการันตีว่าฝั่ง bull กับ bear เป็นจริงพร้อมกัน
 *   ไม่ได้ กฎจึงไม่มีทางขัดแย้งกับตัวเอง (ตัวรันจะนับเป็น conflicts แล้วทิ้งไม้นั้น)
 * · ยิงเฉพาะแท่งที่ "จำนวนเสียงเพิ่งข้ามเส้น k" (แท่งก่อนหน้ายังไม่ถึง) ไม่ใช่ทุกแท่งที่ถึง
 *   ด้วยเหตุผลเดียวกับกฎอื่นในชุดนี้: เงื่อนไขที่เป็นจริงติดกันยาว ๆ ทำให้ไม้ทับกันเอง
 *   แล้วค่าเฉลี่ย R กลายเป็นการวัดความยาวเทรนด์แทนที่จะวัดคุณภาพจุดเข้า
 * · ถ้านับเสียงที่แท่งก่อนหน้าไม่ได้ (ข้อมูลไม่พอ) กฎไม่ยิง — ไม่ปล่อยให้ "คำนวณไม่ได้"
 *   กลายเป็น "แท่งก่อนหน้ายังไม่ถึง k" ซึ่งจะทำให้ NaN แปลงร่างเป็นสัญญาณเข้าไม้
 *
 * ─────────────────────────────── ข้อจำกัดที่รู้ตัว ───────────────────────────────
 *
 * 1. ช่วงมองย้อนหลังทั้งห้าอ่านจากอนุกรมเดียวกัน จึงสัมพันธ์กันสูงมาก การ "เห็นตรงกัน 4/5"
 *    ไม่ได้แปลว่ามีหลักฐานอิสระสี่ชิ้น — ในเทรนด์แรง ๆ ทุกช่วงจะเห็นตรงกันโดยอัตโนมัติ
 *    นี่คือจุดอ่อนหลักของกฎนี้ และเป็นเหตุผลว่าทำไมค่า k ที่สูงจึงไม่ได้แพงอย่างที่คิด
 * 2. ช่วงยาวสุด 120 แท่งแปลว่าบนกรอบ 1H กฎเริ่มทำงานหลังผ่านไปราวห้าวันทำการ และบน 1D
 *    ราวครึ่งปี แท่งช่วงต้นของทุก symbol จึงไม่มีสัญญาณเลยโดยปริยาย
 * 3. เกณฑ์นี้เป็นโมเมนตัมล้วน ไม่มีอะไรบอกว่าราคาแพงไปแล้วหรือยัง เวลาเจอการกลับตัว
 *    หลังเทรนด์ยาว มันจะยิงไม้เข้าไปที่ยอดพอดี — เป็นพฤติกรรมที่คาดไว้แล้ว ไม่ใช่บั๊ก
 * 4. voteMinAtr ใช้ ATR ณ แท่งปัจจุบันเป็นตัวเทียบสำหรับทุกช่วง ทั้งที่การเคลื่อนที่ 120 แท่ง
 *    ควรถูกเทียบกับความผันผวนสะสมของ 120 แท่ง เกณฑ์จึงหลวมกับช่วงยาวและเข้มกับช่วงสั้น
 */

export const meta = {
  id: 'mtf-trend-k-of-n-confluence',
  name: 'นับเสียงข้ามช่วงเวลา k จาก N',
  family: 'confluence',
  needsHtf: false,
  params: {
    /** ช่วงมองย้อนหลัง (หน่วย: แท่งของกรอบเวลาที่กำลังวัด) — หนึ่งช่วง = หนึ่งเสียง */
    horizons: [5, 10, 20, 60, 120],
    /** ต้องมีเสียงเห็นตรงกันอย่างน้อยเท่านี้ (ตั้งให้เกินครึ่งของ N เพื่อกันกฎขัดแย้งตัวเอง) */
    k: 4,
    /** ระยะทางขั้นต่ำของช่วงหนึ่ง ๆ ถึงจะนับเป็นเสียง (หน่วย: เท่าของ ATR ปัจจุบัน) */
    voteMinAtr: 0.5,
  },
};

const NEUTRAL = { bull: false, bear: false, veto: null, score: 0 };
const finite = (v) => Number.isFinite(v);

/**
 * นับเสียงที่แท่งดัชนี i — คืน null เมื่อคำนวณไม่ได้ (ข้อมูลไม่พอ / ATR ใช้ไม่ได้)
 * แยก null ออกจาก {bull:0,bear:0} โดยตั้งใจ เพราะ "ไม่รู้" กับ "รู้ว่าไม่มีเสียง" ต่างกัน
 */
function countVotes(bars, ind, i, horizons, voteMinAtr) {
  if (i < 0) return null;
  const atr = ind.atr[i];
  if (!finite(atr) || !(atr > 0)) return null;
  const close = bars[i].close;
  if (!finite(close)) return null;

  const need = voteMinAtr * atr;
  let bull = 0;
  let bear = 0;
  for (const h of horizons) {
    const j = i - h;
    if (j < 0) return null; // ข้อมูลไม่พอสำหรับช่วงนี้ = นับทั้งชุดไม่ได้
    const past = bars[j].close;
    if (!finite(past)) return null;
    const d = close - past;
    if (d >= need) bull++;
    else if (-d >= need) bear++;
  }
  return { bull, bear };
}

/**
 * @param {{bars: Array, t: number, ind: object, htf: object|null}} ctx
 * @returns {{bull: boolean, bear: boolean, veto: null, score: number}}
 */
export function evaluate(ctx) {
  const { horizons, k, voteMinAtr } = meta.params;
  const { bars, t, ind } = ctx;

  const now = countVotes(bars, ind, t, horizons, voteMinAtr);
  if (!now) return NEUTRAL;
  const prev = countVotes(bars, ind, t - 1, horizons, voteMinAtr);
  if (!prev) return NEUTRAL; // นับแท่งก่อนหน้าไม่ได้ = ตัดสินว่า "เพิ่งข้ามเส้น" ไม่ได้

  const bull = now.bull >= k && prev.bull < k;
  const bear = now.bear >= k && prev.bear < k;

  // ความแรง = เกินเส้น k ไปกี่เสียง จากจำนวนเสียงที่เกินได้มากที่สุด
  const n = horizons.length;
  const span = Math.max(1, n - k + 1);
  let score = 0;
  if (bull) score = Math.min(1, (now.bull - k + 1) / span);
  else if (bear) score = Math.min(1, (now.bear - k + 1) / span);

  return { bull, bear, veto: null, score };
}
