/**
 * วีโต้ #1 — ห้ามซื้อ oversold ในขาลง / ห้ามขาย overbought ในขาขึ้น
 *
 * ─────────────────────────── กฎนี้มาจากแนวคิดอะไร ───────────────────────────
 *
 * ออสซิลเลเตอร์อย่าง RSI/Stochastic ถูกออกแบบมาสำหรับตลาดที่ "ไม่มีใครชนะขาด" — ราคาแกว่ง
 * รอบค่ากลาง ค่าสุดขั้วจึงแปลว่าใกล้กลับตัว แต่ในเทรนด์แรง สมมติฐานนั้นพังทั้งข้อ: RSI 25
 * ในขาลงไม่ได้แปลว่า "ถูกแล้ว" มันแปลว่าฝั่งขายกำลังชนะขาดและยังไม่มีใครมาหยุด การเข้าซื้อ
 * ตรงนั้นคือการเอาสัญญาณของตลาด sideways ไปใช้ในตลาดที่ไม่ sideways
 *
 * กฎนี้จึงไม่ออกสัญญาณเอง (bull=false bear=false เสมอ) หน้าที่มันคือ "ตัดฝั่งที่สวนเทรนด์ทิ้ง"
 * ให้กฎอื่นที่ออกสัญญาณเป็นคนตัดสินใจในสิ่งที่เหลือ
 *
 * ─────────────────────────── ทำไมเกณฑ์ถึงเป็นแบบนี้ ───────────────────────────
 *
 * · เทรนด์ต้องผ่านสามด่านพร้อมกัน ไม่ใช่ด่านเดียว เพราะแต่ละด่านพังคนละแบบ
 *   1) ma50 อยู่คนละฝั่งกับ ma200  — บอกทิศ แต่ตอนตลาดออกข้าง เส้นสองเส้นพันกันไปมา
 *   2) ระยะห่าง |ma50 − ma200| ต้องเกิน maGapMinAtr เท่าของ ATR — กันข้อ 1 ตอนเส้นพันกัน
 *      ใช้ ATR เป็นหน่วยเพราะ 13 สินทรัพย์มีสเกลราคาต่างกันสิบเท่า (EURGBP 0.8 vs XAUUSD 1900)
 *      ระยะห่างเป็น "จุด" จึงเทียบข้ามตัวไม่ได้เลย ต้องหารด้วยความผันผวนของตัวมันเองก่อน
 *   3) ADX ≥ adxMin — ยืนยันว่าทิศที่เห็นมีแรงจริง ไม่ใช่ค่าเฉลี่ยที่ค่อย ๆ ไหล
 *   และราคาปิดต้องอยู่ฝั่งเดียวกับเทรนด์ (ต่ำกว่า ma200 ในขาลง) เพราะเราสนใจ "ตอนนี้ราคาอยู่ไหน"
 *   ไม่ใช่แค่ค่าเฉลี่ยเรียงตัวยังไง
 *
 * · ฝั่ง oversold/overbought ยอมรับสองแหล่ง (RSI หรือ Stochastic %K) แบบ OR เพราะทั้งคู่วัด
 *   "ความสุดขั้ว" คนละสูตร ตัวหนึ่งอาจยังไม่ถึงเส้นในขณะที่อีกตัวถึงแล้ว การรับทั้งคู่ทำให้
 *   วีโต้ครอบคลุมรูปแบบ mean-reversion ได้กว้างขึ้น (วีโต้ที่ครอบคลุมกว้างเกินไปทำให้เสียโอกาส
 *   ซึ่งวัดได้จากตัวเลข — ต่างจากวีโต้ที่แคบเกินไปที่จะเงียบจนดูเหมือนไม่มีอยู่)
 *
 * · เส้น RSI ใช้ 35/65 ไม่ใช่ 30/70 ตามตำรา เพราะกฎนี้ไม่ได้ตัดสินว่า "จะเข้าไม้ไหม"
 *   แต่ตัดสินว่า "นี่กลิ่นของการสวนเทรนด์หรือเปล่า" ซึ่งควรจับได้ตั้งแต่ก่อนถึงเส้นสุดขั้วจริง
 *
 * ─────────────────────────── ข้อจำกัดที่รู้ตัว ───────────────────────────
 *
 * 1. ma200 ต้องใช้ 200 แท่ง — ช่วง 199 แท่งแรกของทุกสินทรัพย์วีโต้นี้เงียบสนิท (NaN = ไม่วีโต้)
 *    บนกรอบ 1D ที่มีแท่งเป็นพัน ไม่กระทบมาก แต่ต้องรู้ว่ามันไม่ใช่ "ไม่มีอะไรผิดปกติ"
 * 2. ADX บอกว่า "มีเทรนด์" แต่ไม่บอกทิศ กฎเลยต้องพึ่ง MA เป็นตัวชี้ทิศ ซึ่งช้าโดยธรรมชาติ
 *    ตอนเทรนด์เพิ่งกลับจริง ๆ กฎนี้จะยังวีโต้ฝั่งที่ถูกต้องอยู่พักใหญ่ (วีโต้ผิดจังหวะกลับตัว)
 *    — นี่คือราคาที่จ่ายเพื่อไม่โดนเทรนด์ลากตายในกรณีส่วนใหญ่ ไม่ใช่ข้อบกพร่องที่แก้ได้ฟรี
 * 3. เกณฑ์ทั้งหมดวัดบน TF เดียวกับที่เทรด ไม่ได้มองภาพใหญ่ (needsHtf=false) เทรนด์ 1H ที่แรง
 *    อาจเป็นแค่การพักตัวของ 1D — กฎนี้แยกสองอย่างนั้นไม่ออก
 * 4. ยังไม่ได้พิสูจน์ว่ามันทำเงิน — ตัวรันวัด "กฎที่ออกสัญญาณ" ส่วนกฎวีโต้ล้วนจะได้ 0 ไม้เสมอ
 *    ค่าของมันต้องวัดตอนเอาไปคู่กับกฎที่ออกสัญญาณจริง ไม่ใช่ตอนวัดเดี่ยว
 *
 * ─────────────────── วัดจริงแล้วได้อะไร (train + validation) ───────────────────
 *
 * วัดด้วยสคริปต์แยก เพราะ rule-lab.mjs ให้ 0 ไม้กับกฎวีโต้ล้วนเสมอโดยโครงสร้าง วิธีวัดคือ
 * เปิดไม้สมมติทั้ง long และ short ที่ทุกแท่ง ด้วยเรขาคณิต/ต้นทุนเดียวกับตัวรันเป๊ะ แล้วเทียบ
 * "ไม้ที่วีโต้ห้าม" กับ "ไม้ที่ปล่อยผ่าน" · ประชากรอ้างอิง 1D: long +0.0344 R · short −0.0392 R
 *
 *   1D  ยิงวีโต้ bull 6.6% · bear 8.7% ของแท่งทั้งหมด
 *       long : ห้าม 4,138 ไม้ +0.0502 R | ปล่อย 58,456 ไม้ +0.0332 R → ห้ามผิดฝั่ง (−0.017 R)
 *       short: ห้าม 5,435 ไม้ −0.0847 R | ปล่อย 57,159 ไม้ −0.0349 R → ห้ามถูก   (+0.050 R)
 *   1H  ยิงวีโต้ bull 6.9% · bear 9.9% — ส่วนต่างทั้งสองฝั่งไม่ถึง 0.008 R คือแทบไม่มีข้อมูล
 *
 * อ่านว่า: ครึ่งเดียวของกฎนี้มีของ — "ห้ามขาย overbought ในขาขึ้น" ได้ผลชัดบน 1D ส่วน
 * "ห้ามซื้อ oversold ในขาลง" กลับตัดไม้ที่ดีกว่าค่าเฉลี่ยทิ้ง ซึ่งตรงข้ามกับที่ตั้งใจ และน่าจะ
 * มาจากชุดข้อมูลนี้ที่ฝั่ง long ได้เปรียบทั้งกระดาน ตัวเลขนี้เป็นหลักฐานหนึ่งชิ้นบนสินทรัพย์ 13 ตัว
 * ที่สัมพันธ์กันสูง ไม่ใช่ข้อพิสูจน์ และยังไม่ได้แตะชุด test
 */

export const meta = {
  id: 'vetoes-mean-reversion-vs-trend',
  name: 'วีโต้: ห้าม mean-reversion สวนเทรนด์',
  family: 'confluence',
  needsHtf: false,
  params: {
    /** เส้น RSI ที่ถือว่าเริ่ม "สุดขั้ว" — กว้างกว่า 30/70 เพราะใช้ดมกลิ่น ไม่ใช่ใช้เข้าไม้ */
    rsiOversold: 35,
    rsiOverbought: 65,
    /** เส้น Stochastic %K — ใช้เป็นทางเลือกคู่ขนานกับ RSI (OR กัน) */
    stochOversold: 20,
    stochOverbought: 80,
    /** ADX ขั้นต่ำที่ถือว่า "มีเทรนด์จริง" */
    adxMin: 20,
    /** |ma50 − ma200| ต้องเกินกี่เท่าของ ATR ถึงจะนับว่าเส้นสองเส้นแยกจากกันจริง */
    maGapMinAtr: 0.5,
    /** ตัวหารแปลง ADX ส่วนเกินเป็นคะแนน 0..1 — ADX สูงกว่า adxMin เท่านี้ถือว่าเต็ม */
    scoreAdxSpan: 30,
  },
};

/** หนีบให้อยู่ 0..1 และกัน NaN หลุดออกไปเป็น score (ตัวรันจะ throw ถ้า score ไม่ใช่ตัวเลขปกติ) */
function clamp01(x) {
  if (!Number.isFinite(x)) return 0;
  if (x < 0) return 0;
  if (x > 1) return 1;
  return x;
}

const NO_VETO = { bull: false, bear: false, veto: null, score: 0 };

/**
 * @param {{bars: Array, t: number, ind: object, htf: object|null}} ctx
 * @returns {{bull: boolean, bear: boolean, veto: null|'bull'|'bear'|'both', score: number}}
 */
export function evaluate(ctx) {
  const p = meta.params;
  const { t, ind } = ctx;

  const close = ctx.bars[t].close;
  const ma50 = ind.ma50[t];
  const ma200 = ind.ma200[t];
  const atr = ind.atr[t];
  const adx = ind.adx[t];

  // ตัดจบด้วย isFinite ก่อนทุกครั้ง ไม่พึ่งพฤติกรรมของ NaN ในตัวเปรียบเทียบ
  // เพราะเงื่อนไขในกฎนี้มีทั้งฝั่ง < และ > ถ้าปล่อยให้ NaN ไหลเข้าไป การกลับเครื่องหมาย
  // ครั้งเดียวจะเปลี่ยนความหมายจาก "ไม่วีโต้" เป็น "วีโต้" โดยไม่มีใครเห็น
  if (!Number.isFinite(close)) return NO_VETO;
  if (!Number.isFinite(ma50) || !Number.isFinite(ma200)) return NO_VETO;
  if (!Number.isFinite(atr) || !(atr > 0)) return NO_VETO;
  if (!Number.isFinite(adx)) return NO_VETO;

  if (!(adx >= p.adxMin)) return NO_VETO;

  const gap = ma50 - ma200;
  if (!(Math.abs(gap) >= p.maGapMinAtr * atr)) return NO_VETO;

  const uptrend = gap > 0 && close > ma200;
  const downtrend = gap < 0 && close < ma200;
  if (!uptrend && !downtrend) return NO_VETO;

  const rsi = ind.rsi[t];
  const k = ind.stoch.k[t];
  const rsiOk = Number.isFinite(rsi);
  const kOk = Number.isFinite(k);

  const oversold = (rsiOk && rsi <= p.rsiOversold) || (kOk && k <= p.stochOversold);
  const overbought = (rsiOk && rsi >= p.rsiOverbought) || (kOk && k >= p.stochOverbought);

  // ความแรงของวีโต้ = ความแรงของเทรนด์ที่กำลังจะถูกสวน ไม่ใช่ความสุดขั้วของออสซิลเลเตอร์
  // เพราะสิ่งที่ทำให้การสวนอันตรายคือเทรนด์ ไม่ใช่ตัวเลข RSI
  const score = clamp01((adx - p.adxMin) / p.scoreAdxSpan);

  if (downtrend && oversold) return { bull: false, bear: false, veto: 'bull', score };
  if (uptrend && overbought) return { bull: false, bear: false, veto: 'bear', score };

  return NO_VETO;
}
