/**
 * chart-timeframes.ts — "หน้ากราฟดูกรอบเวลาไหนได้บ้าง" และแต่ละกรอบขอข้อมูลอย่างไร
 *
 * แยกออกมาเป็นโมดูลของตัวเองเพราะสามฝั่งต้องเห็นตารางเดียวกัน:
 *   · /api/chart      — ตรวจว่า interval ที่ขอมารองรับไหม แล้วแปลงเป็น interval/range ของ Yahoo
 *   · หน้า /chart      — ปุ่มสลับกรอบเวลา + จังหวะ poll
 *   · scripts/test-chart-api.mjs — ยิงทุกกรอบที่ประกาศไว้ ไม่ใช่กรอบที่เทสต์พิมพ์เอง
 * ถ้าตารางนี้อยู่คนละที่กัน วันไหนเพิ่มกรอบใหม่จะมีฝั่งที่ตามไม่ทันโดยไม่มี error ให้เห็น
 *
 * ── ทำไม range แต่ละกรอบเป็นค่านี้ ────────────────────────────────────────────────
 * ลอกจากที่ตัวสแกนใช้จริง (scripts/scan-universe.mjs บรรทัด 134-143) โดยตั้งใจ —
 * กราฟกับสัญญาณจึงอ้างชุดแท่งเดียวกัน ถ้าหน้ากราฟขอช่วงอื่น เจ้าของจะเห็นกราฟคนละชุด
 * กับที่เครื่องยนต์ใช้คิด แล้วหมุดจะดูเหมือนวางผิดที่ทั้งที่ไม่ได้ผิด
 *   15m → 1mo คือ **เพดานของ Yahoo** ไม่ใช่ตัวเลือก (ขอ 3mo ตอบ HTTP 422)
 *
 * ── ทำไม pollMs เป็นค่านี้ ────────────────────────────────────────────────────────
 * หลักคือ "ให้แท่งที่กำลังก่อตัวขยับพอให้รู้สึกว่ากราฟมีชีวิต แต่ไม่ยิงซ้ำจนเปลืองเปล่า"
 * จึงตั้งให้เป็นเศษส่วนเล็ก ๆ ของความยาวหนึ่งแท่ง และต้องไม่สั้นกว่าอายุแคชฝั่ง server
 * (CHART_CACHE_SEC = 30 วิ) ไม่งั้นคำขอที่เกินมาจะได้คำตอบเดิมกลับไปเฉย ๆ
 *   15m: 60 วิ  = 1/15 ของแท่ง  ·  1H: 120 วิ = 1/30 ของแท่ง  ·  1D: 300 วิ
 * รายวันตั้งห่างสุดเพราะแท่งรายวันแทบไม่ขยับรูปร่าง สิ่งที่เปลี่ยนคือ "ราคาล่าสุด" อย่างเดียว
 */

/**
 * แท่งเทียนในรูปที่ /api/chart ส่งออกและตัววาดกราฟรับเข้า
 *
 * `t` เป็น epoch **วินาที** (ไม่ใช่มิลลิวินาที ไม่ใช่ ISO) เพราะเป็นรูปที่ตัววาดกราฟ
 * รับตรง ๆ อยู่แล้ว และเลน 15m ส่งได้ถึง ~2,600 แท่งต่อคำขอ — รูป ISO ทำให้ก้อนใหญ่ขึ้น
 * เกือบเท่าตัวโดยไม่ได้อะไรกลับมา · ไม่มี volume เพราะหน้านี้ไม่ได้วาดมัน
 *
 * ⚠ นี่คือรูปเฉพาะของเลนกราฟ ไม่ใช่ CandleData ของทั้งระบบ — ฝั่งที่ต้องคำนวณให้ตรงกับ
 *   สัญญาณต้องไปเอา CandleData จาก fetchChart เอง อย่าหยิบรูปนี้ไปใช้แทน
 */
export interface ChartBar {
  /** epoch วินาที ของเวลาเปิดแท่ง */
  t: number;
  o: number;
  h: number;
  l: number;
  c: number;
}

export interface ChartTimeframe {
  /** ค่าที่ส่งเป็น query string ให้ /api/chart และเป็น id ของปุ่มบนหน้าเว็บ */
  key: '15m' | '1H' | '1D';
  /** ป้ายบนปุ่ม */
  label: string;
  interval: ChartInterval;
  range: ChartRange;
  /** ความยาวหนึ่งแท่งเป็นวินาที — ใช้ทั้งจัดหมุดและอธิบายจังหวะ poll */
  barSec: number;
  /** ทุกกี่มิลลิวินาทีถึงจะดึงใหม่ (หยุดเมื่อแท็บถูกซ่อน) */
  pollMs: number;
}

export const CHART_TIMEFRAMES: readonly ChartTimeframe[] = [
  { key: '15m', label: '15 นาที', interval: '15m', range: '1mo', barSec: 900, pollMs: 60_000 },
  { key: '1H', label: '1 ชั่วโมง', interval: '1h', range: '3mo', barSec: 3600, pollMs: 120_000 },
  { key: '1D', label: '1 วัน', interval: '1d', range: '1y', barSec: 86_400, pollMs: 300_000 },
];

/**
 * กรอบเริ่มต้นของหน้ากราฟ — 15m ตามที่เจ้าของสั่ง (เลนที่เขาเฝ้าดูจริง)
 * เขียนเป็นค่าคงที่แทนการหยิบ CHART_TIMEFRAMES[0] เพื่อให้การสลับลำดับปุ่ม
 * ในตารางข้างบนไม่เผลอเปลี่ยนกรอบเริ่มต้นไปด้วย
 */
export const DEFAULT_TIMEFRAME_KEY: ChartTimeframe['key'] = '15m';

/**
 * แปลงค่าที่ผู้ใช้/ผู้เรียกส่งมาเป็นกรอบเวลาที่รองรับ — ไม่รู้จัก = null (ห้ามเดา)
 *
 * เทียบแบบไม่สนตัวพิมพ์เพราะ query string จากมือถือมาได้ทั้ง `1h` และ `1H`
 * แต่ **ไม่รับค่าที่ไม่มีในตาราง** เด็ดขาด — route ต้องตอบ 400 ไม่ใช่ถอยไปกรอบอื่นเงียบ ๆ
 * แล้วให้ผู้ใช้ดูกราฟคนละกรอบกับที่ปุ่มบอก
 */
export function resolveTimeframe(key: string | null | undefined): ChartTimeframe | null {
  const k = String(key ?? '').trim().toLowerCase();
  if (!k) return null;
  return CHART_TIMEFRAMES.find((t) => t.key.toLowerCase() === k) ?? null;
}

/**
 * เพดานจำนวนแท่งที่ /api/chart ส่งออกต่อหนึ่งคำขอ (เอาแท่งท้ายสุด ตัดของเก่าทิ้ง)
 *
 * ── ทำไมต้องมีเพดาน (วัดมาแล้ว ไม่ใช่การเดา) ─────────────────────────────────────
 * เลน 15m ขอ range=1mo จาก Yahoo ซึ่งคืน ~2,200 แท่ง วัดขนาดสายจริงของคำตอบทั้งก้อน
 * ที่ 2,209 แท่งได้ 230.8 KB (gzip 72.9 KB) และหน้ากราฟ poll ทุก 60 วินาที
 * = ~4.4 MB ต่อชั่วโมงหลังบีบอัด บนเน็ตมือถือของเจ้าของ ทั้งที่จอกว้าง 375px
 * แสดงได้สูงสุด ~140 แท่งในคราวเดียว — ที่เหลือคือค่าเน็ตที่จ่ายไปโดยไม่มีใครได้ดู
 *
 * ── ทำไม 1,000 ถึงปลอดภัยกับหมุด (พิสูจน์ได้ ไม่ต้องเดาว่าตลาดหยุดกี่ชั่วโมง) ────────
 * ตัวจัดหมุดตัดสัญญาณที่ "เก่ากว่าแท่งแรกของกราฟ" ทิ้ง (ดู buildSignalMarkers ด่าน 6)
 * เพดานนี้จึงต้องครอบคลุมอายุสัญญาณที่ยาวที่สุดในระบบเสมอ ซึ่งคือ 7 วัน (1D — ดู
 * SIGNAL_TTL_MS ใน src/lib/signal-engine.ts) มิฉะนั้นหมุดของใบที่ยังเปิดอยู่จะหายไปเงียบ ๆ
 *   1,000 แท่ง × ความยาวแท่ง = เวลา **ซื้อขาย** ที่ครอบคลุม ซึ่งเป็นขอบล่างของเวลาปฏิทิน
 *   เสมอ (ตลาดหยุดเมื่อไหร่ ช่วงปฏิทินยิ่งยาวขึ้น ไม่มีทางสั้นลง)
 *     15m → 1,000 × 900 วิ  = 10.4 วัน   ≥ 7 วัน ✓
 *     1H  → 1,000 × 3600 วิ = 41.7 วัน   ≥ 7 วัน ✓
 *     1D  → 1,000 × 86400 วิ = 1,000 วัน ≥ 7 วัน ✓ (และ 1D ขอมาแค่ ~250 แท่ง ไม่ถึงเพดาน)
 * scripts/test-chart-api.mjs ยืนยันความสัมพันธ์นี้จากตารางจริง ไม่ใช่จากเลขที่เทสต์พิมพ์เอง
 * ⚠ ถ้าวันไหนยืดอายุสัญญาณให้ยาวกว่า 10.4 วัน ต้องมาขยายเพดานนี้ด้วย (เทสต์จะแดงให้เห็น)
 */
export const CHART_MAX_BARS = 1000;

