/** ราคาล่าสุดเก่ากว่านี้ = ตลาดไม่ได้ซื้อขายอยู่ (ที่มาของเลขอยู่หัวไฟล์) */
export const MARKET_CLOSED_AFTER_SEC = 30 * 60;

export interface MarketSessionVerdict {
  /** true = ออกสัญญาณได้ */
  open: boolean;
  /** อายุของการซื้อขายครั้งล่าสุด (วินาที) — null เมื่อไม่มีข้อมูลเวลาเลย */
  staleSec: number | null;
  /**
   * fresh   = มีการซื้อขายเมื่อไม่นาน
   * closed  = ไม่มีการซื้อขายนานเกินเกณฑ์ (สุดสัปดาห์ / วันหยุด / ช่วงพัก)
   * unknown = ไม่รู้เวลาซื้อขายเลย — **ปล่อยผ่าน** (เหตุผลที่ marketSessionState)
   */
  state: 'fresh' | 'closed' | 'unknown';
}

/**
 * ตลาดเปิดอยู่ไหม ณ เวลา nowMs
 *
 * @param lastTradeSecs เวลาซื้อขายล่าสุด (epoch วินาที) จากทุกคำขอในรอบนี้ — ใช้ตัวที่ใหม่สุด
 *                      เพราะสามกรอบเวลาถูกดึงห่างกันไม่กี่มิลลิวินาที ตัวไหนใหม่กว่าก็คือความจริงล่าสุด
 *
 * ⚠ ไม่รู้เวลาเลย = **ปล่อยผ่าน ไม่ใช่ปิดกั้น** โดยตั้งใจ:
 *   ปิดกั้น → วันไหน Yahoo ถอดฟิลด์นี้ออก สัญญาณจะหายทั้งหมดแบบเงียบ ๆ และหน้าเว็บ
 *            ไม่มีทางรู้ (ราคายังอัปเดต scan-health ยังเขียว) เจ้าของจะคิดว่า "ไม่มีจังหวะ" ไปหลายวัน
 *   ปล่อยผ่าน → แย่สุดคือกลับไปเป็นพฤติกรรมก่อนมีด่านนี้ ซึ่งกันซ้ำตามเนื้อหา (sameSetupKey)
 *            ยังกันการเด้งซ้ำไว้ได้อีกชั้น — ผู้เรียกต้องเตือนดัง ๆ เมื่อได้ state 'unknown'
 */
export function marketSessionState(
  nowMs: number,
  lastTradeSecs: ReadonlyArray<number | null | undefined>
): MarketSessionVerdict {
  const valid = lastTradeSecs.filter((s): s is number => typeof s === 'number' && Number.isFinite(s) && s > 0);
  if (!valid.length || !Number.isFinite(nowMs)) return { open: true, staleSec: null, state: 'unknown' };

  const latest = Math.max(...valid);
  // นาฬิกาของเครื่องที่รันเดินช้ากว่า Yahoo นิดหน่อยได้ → อายุติดลบ ปัดเป็นศูนย์ ไม่ใช่ถือว่าผิดปกติ
  const staleSec = Math.max(0, Math.round(nowMs / 1000 - latest));
  return staleSec > MARKET_CLOSED_AFTER_SEC
    ? { open: false, staleSec, state: 'closed' }
    : { open: true, staleSec, state: 'fresh' };
}

/**
 * แท่งปิดล่าสุดของกรอบเล็กเป็น "แท่งปัจจุบัน" หรือ "แท่งค้างจากก่อนตลาดปิด"
 *
 * ปิดช่องที่ด่านตลาดปิดปิดไม่ถึง: ตอนตลาดเพิ่งเปิดคืนวันอาทิตย์ ~22:00Z เวลาซื้อขายล่าสุด
 * สดทันที (ด่านเปิด) แต่แท่งปิดใบสุดท้ายยังเป็นศุกร์ 20:45Z ไปอีก ~25 นาทีจนกว่าแท่งแรก
 * ของสัปดาห์จะปิดและโผล่ใน Yahoo · ถ้าปล่อย รอบนั้นจะออกสัญญาณจากแท่งศุกร์ซ้ำอีกใบ
 *
 * วัดจากความต่าง "เวลาซื้อขายล่าสุด − ปลายแท่งปิดใบสุดท้าย" ไม่ใช่ "ตอนนี้ − ปลายแท่ง"
 * เพื่อไม่ให้ความหน่วง ~10 นาทีของ Yahoo และความช้าของ GitHub ปนเข้ามา
 * วัดจริง 2026-09-14 06:11Z ตลาดเปิด: 15m ห่าง 0.03 ชม. · 1H ห่าง 0.03 ชม.
 * เกณฑ์ 2 แท่ง เผื่อกรณีแท่งก่อนหน้าแท่งสดถูกนับเป็นแท่งสด (lastTradeAt ตรงกับเวลาแท่ง)
 *
 * ⚠ ห้ามใช้กับ 1D: แท่งรายวันของ Yahoo ประทับเวลา 04:00Z และปิดตอน 03:59Z ของวันถัดไป
 *   เช้าวันจันทร์ปกติแท่งปิดใบสุดท้ายคือแท่งศุกร์ ห่างจากการซื้อขาย 50 ชม. (วัดจริงวันเดียวกัน)
 *   กติกานี้จะปิด 1D ทั้งวันจันทร์ · 1D ได้ด่านตลาดปิดกับกันซ้ำตามเนื้อหาคุ้มครองแทน
 */
export function intradayBarIsCurrent(
  lastClosedBarStartSec: number,
  barSec: number,
  lastTradeSec: number | null | undefined
): boolean {
  if (typeof lastTradeSec !== 'number' || !Number.isFinite(lastTradeSec) || lastTradeSec <= 0) return true;
  if (!Number.isFinite(lastClosedBarStartSec) || !(barSec > 0)) return true;
  const lagSec = lastTradeSec - (lastClosedBarStartSec + barSec);
  return lagSec <= 2 * barSec;
}

/** ค่าที่ต้องใช้ระบุ "เซ็ตอัพเดียวกัน" — เป็นทั้งใบใหม่ในหน่วยความจำและแถวเก่าจากตาราง signals */
export interface SetupFields {
  user_id: string;
  symbol: string;
  timeframe: string;
  action: string;
  entry_price: number | string;
  stop_loss: number | string;
  take_profit: number | string;
}

/** กันซ้ำตามเนื้อหาย้อนหลังเท่านี้ — เท่ากับอายุยาวสุดของใบ (FLIP_LOOKBACK_HOURS ในตัวสแกน) */
export const SAME_SETUP_LOOKBACK_HOURS = 7 * 24;

/**
 * กุญแจของ "เซ็ตอัพ" — ใบที่กุญแจตรงกัน คือใบเดียวกันที่ถูกคำนวณซ้ำจากข้อมูลชุดเดิม
 *
 * ตัวกันซ้ำเดิมจำด้วยนาฬิกา (15m/1H 4 ชม. · 1D 20 ชม.) แต่ตัวตนของสัญญาณผูกกับ "แท่ง"
 * แท่งค้างนานกว่าหน้าต่างเมื่อไหร่ ใบเดิมก็กลายเป็นใบใหม่ — ไม่ใช่แค่สุดสัปดาห์:
 * 1D หน้าต่าง 20 ชม. แต่แท่งอยู่ 24 ชม. จึงมีช่อง 4 ชม./วันที่ออกซ้ำได้อยู่แล้ว
 *
 * ทำไมใช้ราคาเข้า/SL/TP แทนการเก็บเวลาแท่งลงตาราง: ตาราง signals ไม่มีคอลัมน์เวลาแท่ง
 * การเพิ่มต้องให้เจ้าของรัน migration เอง ส่วนสามตัวเลขนี้ถูกบันทึกอยู่แล้วทุกใบ
 * และเป็นฟังก์ชันของแท่งล้วน ๆ (entry = ราคาปิด · SL/TP มาจาก ATR 14 แท่ง) —
 * แท่งใหม่ที่ให้ทั้งสามค่าเท่าเดิมถึงทศนิยมตำแหน่งที่ 4 แทบเป็นไปไม่ได้
 * วัดจากประวัติจริง: ของซ้ำ 8 ใบที่เจอ ตรงกันทั้งสามค่าทุกใบ และไม่มีคู่ไหนที่เป็นคนละแท่ง
 *
 * ปัดทศนิยม 4 ตำแหน่งทั้งสองฝั่ง เพราะแถวจาก Postgres (numeric) กับค่าในหน่วยความจำ
 * (float เต็ม เช่น 4408.89990234375) ต้องได้กุญแจเดียวกัน
 */
export function sameSetupKey(s: SetupFields): string | null {
  const nums = [s.entry_price, s.stop_loss, s.take_profit].map((v) => Number(v));
  if (nums.some((n) => !Number.isFinite(n))) return null;
  const r4 = (n: number) => (Math.round(n * 1e4) / 1e4).toFixed(4);
  return [s.user_id, String(s.symbol).toUpperCase(), s.timeframe, s.action, ...nums.map(r4)].join('|');
}
