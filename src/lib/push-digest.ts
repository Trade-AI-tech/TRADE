export interface ThrottleVerdict {
  send: boolean;
  /** เหตุผลภาษาไทย เอาไปใส่ log ของ cron ได้เลย ไม่ต้องแปลอีกรอบ */
  reason: string;
  /** ต้องรออีกกี่มิลลิวินาทีถึงจะส่งได้ — 0 เมื่อส่งได้เลย */
  waitMs: number;
}

export interface RoundThrottleInput {
  nowMs: number;
  /** เวลาที่ "แจ้งเตือนสัญญาณ" ออกไปสำเร็จครั้งล่าสุด — null = ยังไม่เคยแจ้งเลย */
  lastNotifiedAtMs: number | null;
  /** จำนวนสัญญาณที่จะแจ้งรอบนี้ (หลังกรอง/ยุบซ้ำแล้ว) */
  signalCount: number;
  /**
   * รอบที่ถูกกันไว้ "เก็บตกได้รอบหน้า" หรือไม่ — มีผลกับข้อความเหตุผลอย่างเดียว ไม่ใช่การตัดสิน
   *
   * true (ค่าเริ่มต้น) = เส้นทางปกติ มีคอลัมน์ push_sent คอยจำว่าแถวไหนยังไม่เคยแจ้ง
   * false = โหมดถอย (ยังไม่ได้รัน migration 006) รอบที่ถูกกันจะไม่ได้แจ้งอีกเลย
   *
   * ทำไมต้องแยกข้อความ: log ของ cron คือที่เดียวที่เจ้าของจะรู้ว่าเกิดอะไรขึ้น
   * ถ้าเขียนว่า "สัญญาณไม่หาย" ทั้งที่โหมดถอยทำให้หายจริง = โกหกในที่ที่ตรวจสอบยากที่สุด
   */
  recoverable?: boolean;
}

/** "45 วินาที" / "12 นาที" — ต่ำกว่า 1 นาทีต้องไม่ปัดเป็น "0 นาที" ซึ่งอ่านแล้วงง */
function humanGap(ms: number): string {
  const s = Math.max(0, Math.round(ms / 1000));
  return s < 60 ? `${s} วินาที` : `${Math.round(s / 60)} นาที`;
}

/**
 * ตัวคุมความถี่ของเส้นทางปกติ: **หนึ่งช่องชั่วโมง = แจ้งเตือนได้ครั้งเดียว**
 *
 * ทำไมนับเป็น "ช่อง" ไม่ใช่ "ห่างกันกี่นาที"
 * ────────────────────────────────────────
 * สเปกเจ้าของคือ "ชั่วโมงนึงแจ้งเตือน 1 ครั้ง" ซึ่งแปลตรงตัวได้เป็นช่องชั่วโมงพอดี
 * ถ้าใช้ "ห่างกัน >= 60 นาที" แทน จะเจอปัญหาจริงข้อนี้: GitHub Actions ออกตัวช้าได้หลายนาที
 * รอบที่ช้าไป 10 นาทีจะทำให้ระยะห่างกับรอบถัดไปเหลือ ~50 นาที แล้วรอบถัดไปถูกกันทิ้ง
 * = เจ้าของต้องรออีกชั่วโมงเต็มเพื่อดูสัญญาณที่ควรได้ตอนนี้ ซึ่งฆ่าไม้ 1 ชม. ทิ้งทั้งไม้
 * การนับเป็นช่องไม่มีปัญหานี้ เพราะแต่ละรอบตกคนละช่องอยู่แล้วไม่ว่าจะช้าไปกี่นาที
 *
 * ⚠ ตัวนี้ปลอดภัยได้เพราะรอบที่ถูกกัน "ไม่ทำให้สัญญาณหาย" — แถวใน signals ยังมี
 *   push_sent = false อยู่ รอบหน้าจะกวาดมาแจ้งให้เอง (ดู sendPendingSignalsToUser)
 *   ถ้าวันไหนมีคนเอาตัวนี้ไปใช้ในเส้นทางที่ไม่มีการเก็บตก มันจะกลายเป็นตัวทำสัญญาณหายทันที
 *
 * ไม่มี "ประตูหนีสำหรับสัญญาณแรงมาก" โดยตั้งใจ: ประตูนั้นคือสาเหตุที่วัดได้ว่า
 * เจ้าของโดนเด้ง ~6 ครั้ง/วัน (สูงสุด 12) ซึ่งเกินสเปก และตอนนี้การรอถึงรอบหน้า
 * ไม่ได้แปลว่าพลาดสัญญาณอีกต่อไป แค่ช้าลงหนึ่งรอบ
 */
export function roundThrottleVerdict({
  nowMs,
  lastNotifiedAtMs,
  signalCount,
  recoverable = true,
}: RoundThrottleInput): ThrottleVerdict {
  if (signalCount <= 0) {
    return { send: false, reason: 'ไม่มีสัญญาณให้แจ้ง', waitMs: 0 };
  }
  if (lastNotifiedAtMs === null) {
    return { send: true, reason: 'ยังไม่เคยแจ้งเตือนสัญญาณให้ผู้ใช้นี้', waitMs: 0 };
  }

  // ท้ายข้อความบอกชะตากรรมของสัญญาณรอบนี้ตามความจริงของแต่ละโหมด — ห้ามเขียนเหมือนกัน
  const fate = recoverable
    ? '(สัญญาณไม่หาย — ยังค้างเป็น "ยังไม่แจ้ง" ใน signals รอบหน้าเก็บตกให้)'
    : '(⚠ โหมดถอย: สัญญาณรอบนี้จะ "ไม่ได้เก็บตก" รอบหน้า — รัน supabase/migrations/006_signal_push_state.sql เพื่อให้เก็บตกได้)';

  const windowMs = PUSH_DIGEST_CONFIG.TAG_WINDOW_MINUTES * 60_000;
  const nowSlot = Math.floor(nowMs / windowMs);
  const lastSlot = Math.floor(lastNotifiedAtMs / windowMs);

  // ── ด่านที่ 1: ช่องชั่วโมงเดียวกัน = แจ้งไปแล้ว ────────────────────────────
  // ใช้ <= ไม่ใช่ === เพื่อกันนาฬิกา DB เดินนำเครื่องที่รัน (lastSlot > nowSlot)
  // ถ้าใช้ === เคสนั้นจะถูกตีความว่า "คนละช่อง" แล้วปล่อยให้ยิงซ้ำได้ทันที
  if (nowSlot <= lastSlot) {
    const waitMs = Math.max(0, (lastSlot + 1) * windowMs - nowMs);
    return {
      send: false,
      reason: `ชั่วโมงนี้แจ้งเตือนไปแล้ว รออีก ${Math.ceil(waitMs / 60_000)} นาที ${fate}`,
      waitMs,
    };
  }

  // ── ด่านที่ 2: ต่อให้คนละช่อง ก็ต้องห่างจากใบก่อนพอ ────────────────────────
  //
  // ช่องชั่วโมงเป็นเส้นตายตัวตามเวลา UTC ไม่ได้นับระยะห่างเลย 13:59:59Z → 14:00:01Z
  // จึงเป็นคนละช่องทั้งที่ห่างกัน 2 วินาที (วัดจริงแล้วเด้งสองใบซ้อน และ tag คนละค่า
  // ทั้งสองใบจึงค้างบนจอล็อกพร้อมกัน) ด่านนี้คือพื้นรองที่ทำให้เคสนั้นเป็นไปไม่ได้
  //
  // ทำไมไม่เอาด่านนี้มาแทนช่องชั่วโมงไปเลย: กฎ "ห่างกัน >= 60 นาที" ล้วน ๆ มีปัญหา
  // การเลื่อนสะสม — รอบที่ออกช้า 10 นาทีจะบีบระยะห่างของรอบถัดไปเหลือ ~50 นาที
  // แล้วรอบถัดไปถูกกันทิ้งทั้งที่เป็นคนละชั่วโมง (ดูเหตุผลเต็มที่ MIN_NOTIFY_GAP_MS)
  const elapsed = nowMs - lastNotifiedAtMs;
  const gap = PUSH_DIGEST_CONFIG.MIN_NOTIFY_GAP_MS;
  if (elapsed < gap) {
    const waitMs = gap - elapsed;
    return {
      send: false,
      reason:
        `เพิ่งแจ้งเตือนไปเมื่อ ${humanGap(elapsed)} ที่แล้ว (ข้ามช่องชั่วโมงมาแต่ชิดกันเกินไป) ` +
        `รออีก ${Math.ceil(waitMs / 60_000)} นาที ${fate}`,
      waitMs,
    };
  }

  return { send: true, reason: 'เข้าช่วงชั่วโมงใหม่แล้ว และห่างจากใบก่อนพอ', waitMs: 0 };
}

export interface ThrottleInput {
  nowMs: number;
  /** เวลาที่ push ถึงเครื่องผู้ใช้สำเร็จครั้งล่าสุด — null = ไม่เคยส่งเลย */
  lastPushAtMs: number | null;
  signals: Signal[];
}

/**
 * ตัวจำกัดความถี่ของ "โหมดถอย" (ยังไม่ได้รัน migration 006) — กติกาเดียวกับเส้นทางปกติ
 *
 * ⚠ นี่คือเส้นทางที่ทำงานอยู่ "ตอนนี้" ไม่ใช่ทางสำรอง: วัดกับฐานข้อมูลจริง 2026-08-17
 *   ได้ 42703 (column signals.push_sent does not exist) = ยังไม่ได้รัน 006
 *
 * เดิมตัวนี้ใช้กติกาคนละชุด (ห่างกัน 10 นาที + ประตูหนีให้ very_strong) ด้วยเหตุผลว่า
 * โหมดถอยกันไว้แล้วสัญญาณหายถาวร จึงเลือกข้าง "ยอมเด้งถี่ ดีกว่ายอมหาย"
 * แต่วัดจริงแล้วมันแปลว่า 6 ครั้ง/55 นาที (เกินสเปกที่เจ้าของสั่งไว้ 6 เท่า)
 * และ very_strong เปิดประตูได้ทุกครั้ง = 6 ครั้ง/15 นาที — เจ้าของสั่งว่า
 * "ชั่วโมงนึงแจ้งเตือน 1 ครั้ง" โดยไม่ได้ยกเว้นโหมดไหนไว้ กติกาจึงต้องเหมือนกันทั้งสองโหมด
 *
 * ที่ยอมแลก และต้องพูดให้ชัด: ในโหมดถอย รอบที่ถูกกัน "ไม่ได้เก็บตกรอบหน้า" จริง ๆ
 * สัญญาณของรอบนั้นจะไม่มีวันถูกแจ้งอีก (แต่ยังอยู่ในตาราง signals และโผล่บนหน้า /signals
 * ด้วยลำดับเดียวกับในแจ้งเตือน) — ทางแก้ถาวรคือรัน 006 ไม่ใช่ผ่อนความถี่ให้หลวมลง
 * ข้อความ reason จึงบอกเรื่องนี้ทุกครั้งที่กัน เพื่อให้เห็นใน log ของ cron
 *
 * ⚠ ข้อจำกัดของนาฬิกาในโหมดนี้: lastPushAtMs มาจาก push_subscriptions.last_used_at
 *   ซึ่งขยับทุกครั้งที่มี push ออกไปชนิดไหนก็ได้ รวมถึงปุ่ม "ทดสอบส่งแจ้งเตือน"
 *   กดปุ่มทดสอบตอน 10:20 จึงกินโควตาแจ้งเตือนของช่วง 10:00 ไปด้วย
 *   (เส้นทางปกติไม่มีปัญหานี้ เพราะใช้ signals.push_sent_at ที่ปุ่มทดสอบไม่แตะ)
 */
export function throttleVerdict({ nowMs, lastPushAtMs, signals }: ThrottleInput): ThrottleVerdict {
  return roundThrottleVerdict({
    nowMs,
    lastNotifiedAtMs: lastPushAtMs,
    signalCount: signals.length,
    // โหมดถอยไม่มีคอลัมน์ push_sent ให้เก็บตก — ข้อความต้องบอกความจริงข้อนี้
    recoverable: false,
  });
}
