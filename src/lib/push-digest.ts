/**
 * อัตราส่วนผลตอบแทนต่อความเสี่ยง — คืน null เมื่อคำนวณไม่ได้ (SL ทับราคาเข้า/ค่าเพี้ยน)
 * ห้ามคืน 0 แทน null เพราะ 0 แปลว่า "วัดแล้วได้ศูนย์" ซึ่งคนละความหมาย
 */
export function riskReward(signal: Signal): number | null {
  const risk = Math.abs(signal.entry_price - signal.stop_loss);
  const reward = Math.abs(signal.take_profit - signal.entry_price);
  if (!Number.isFinite(risk) || !Number.isFinite(reward) || risk <= 0) return null;
  return reward / risk;
}

/**
 * คะแนนความสำคัญของสัญญาณ (0 ถึง MAX_SIGNAL_SCORE)
 *
 * เกณฑ์ที่ใช้ และเหตุผลของน้ำหนัก — เรียงจากหนักไปเบา
 *  1. ความแรง 40 แต้ม — ตัวชี้คุณภาพที่ตรงที่สุดที่เครื่องคำนวณให้มา
 *  2. ความมั่นใจ 30 แต้ม — ละเอียดกว่าความแรง ใช้แยกตัวที่ความแรงเท่ากัน
 *  3. ผลตอบแทนต่อความเสี่ยง 20 แต้ม — ตัดเพดานที่ 3R เพราะเกินกว่านั้นมักมาจาก
 *     SL ที่แคบผิดปกติ ไม่ใช่ไม้ที่ดีกว่าจริง ปล่อยไม่ตัดเพดานจะดันไม้เสี่ยงขึ้นบนสุด
 *  4. ความเน่าเร็วตาม timeframe 6 แต้ม — ตัวตัดสินเสมอ ไม่ใช่ตัวชี้คุณภาพ
 *     จงใจให้ต่ำกว่าระยะห่างของขั้นความแรง (14) เพื่อไม่ให้ 1H อ่อน ๆ
 *     แซง 1D ที่แรงกว่าขึ้นไปอยู่บนสุด
 *
 * ทำไมเอาคุณภาพนำความรีบ: ตอนนี้ระบบยังพิสูจน์ไม่ได้ว่ามี edge (profit factor 0.98)
 * หน้าที่ของลำดับจึงคือดัน "ตัวที่มีโอกาสคุ้มที่สุด" ขึ้นบนสุด ไม่ใช่ตัวที่ด่วนที่สุด
 */
export function scoreSignal(signal: Signal): number {
  const strength = STRENGTH_SCORE[signal.strength] ?? 0;

  const rawConfidence = Number.isFinite(signal.confidence) ? signal.confidence : 0;
  const confidence = (Math.min(100, Math.max(0, rawConfidence)) / 100) * 30;

  const rr = riskReward(signal);
  const rrScore = rr === null ? 0 : (Math.min(rr, 3) / 3) * 20;

  const urgency = TIMEFRAME_URGENCY[signal.timeframe] ?? TIMEFRAME_URGENCY_DEFAULT;

  return strength + confidence + rrScore + urgency;
}

/**
 * เรียงสัญญาณจากสำคัญสุดไปน้อยสุด
 *
 * ลำดับของกุญแจ (บนลงล่าง):
 *  0. คะแนนความเร็ว — "โอกาสที่ไม้จะจบภายใน ~1 ชม." จาก src/lib/speed-scorecard.ts
 *     มาก่อนทุกอย่างเพราะเป็นคำสั่งตรงของเจ้าของ ("เรียงลำดับตัวที่ได้กำไรจบภายใน 1 ชั่วโมง")
 *     ⚠ ไม่ส่ง scorer เข้ามา (หรือไฟล์นั้นยังไม่มี) → ทุกตัวได้ 0 → ลำดับเท่ากับของเดิมเป๊ะ
 *       ตั้งใจให้เป็นแบบนี้ เพื่อให้ระบบทำงานถูกต้องอยู่แล้วก่อนที่งานวิจัยจะเสร็จ
 *  1-4. คะแนนคุณภาพ (scoreSignal) แล้วค่อยความมั่นใจ / สัญลักษณ์ / timeframe / id
 *
 * ต้องได้ลำดับเดิมเสมอไม่ว่าตัวสแกนจะเจอเรียงมาแบบไหน — ลำดับที่ขึ้นกับ
 * "บังเอิญเจอก่อน" คือลำดับที่อธิบายให้เจ้าของฟังไม่ได้ และเปลี่ยนไปมาทุกรอบ
 * จึงมีตัวตัดสินเสมอไล่ลงไปจนถึง id ซึ่งไม่มีทางซ้ำ
 */
export function rankSignals(signals: Signal[], scorer?: SpeedScorer | null): Signal[] {
  const speedOf = makeSpeedLookup(scorer);
  return [...signals].sort((a, b) => {
    const speedDiff = speedOf(b) - speedOf(a);
    if (Math.abs(speedDiff) > 1e-9) return speedDiff;

    const diff = scoreSignal(b) - scoreSignal(a);
    // คะแนนเป็นทศนิยม — ต่างกันจิ๊บจ๊อยระดับ 1e-9 ให้ถือว่าเท่ากัน แล้วไปตัดสินด้วยเกณฑ์ถัดไป
    if (Math.abs(diff) > 1e-9) return diff;
    if (b.confidence !== a.confidence) return b.confidence - a.confidence;
    if (a.symbol !== b.symbol) return a.symbol < b.symbol ? -1 : 1;
    if (a.timeframe !== b.timeframe) return a.timeframe < b.timeframe ? -1 : 1;
    return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
  });
}

/**
 * ยุบสัญญาณที่เป็น "การตัดสินใจเดียวกัน" ให้เหลือตัวเดียว
 *
 * XAUUSD ซื้อ 1D กับ XAUUSD ซื้อ 1H ที่โผล่รอบเดียวกัน สำหรับคนเทรดคือเรื่องเดียวกัน
 * ถ้าไม่ยุบ ชุดแจ้งเตือนจะเปลืองบรรทัดไปกับชื่อซ้ำ แล้วดันตัวอื่นตกขอบ
 * ต้องเรียกหลัง rankSignals เสมอ — ตัวที่เก็บไว้คือตัวคะแนนสูงสุดของคู่นั้น
 */
export function collapseDuplicates(rankedSignals: Signal[]): Signal[] {
  const seen = new Set<string>();
  const out: Signal[] = [];
  for (const s of rankedSignals) {
    const key = `${s.symbol}|${s.action}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(s);
  }
  return out;
}

