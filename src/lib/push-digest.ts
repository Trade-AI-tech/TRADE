/**
 * เครื่องหมายผสมของไทย (สระบน/ล่าง/วรรณยุกต์) + ตัวควบคุมของ emoji
 * ถ้าตัดข้อความแล้วเหลือพวกนี้ห้อยท้าย จะกลายเป็นสระลอยอ่านไม่ออก ต้องตัดทิ้งด้วย
 */
const DANGLING_MARK = /[ัิ-ฺ็-๎️‍]$/;

/**
 * ตัดข้อความให้ไม่เกินงบ โดยนับเป็น "ตัวอักษรที่คนเห็น" (code point)
 * ไม่ใช่ .slice() ธรรมดา เพราะ emoji เป็นคู่ surrogate — ตัดกลางแล้วได้อักขระพัง
 */
export function clip(text: string, maxChars: number): string {
  const chars = Array.from(text);
  if (chars.length <= maxChars) return text;

  // เผื่อที่ให้ … หนึ่งตัว แล้วเล็มเครื่องหมายผสม/ช่องว่างที่ห้อยท้ายออก
  let out = chars.slice(0, Math.max(0, maxChars - 1)).join('');
  while (out.length > 0 && DANGLING_MARK.test(out)) out = Array.from(out).slice(0, -1).join('');
  return `${out.trimEnd()}…`;
}

/** จำนวนตัวอักษรที่คนเห็นจริง — emoji นับเป็น 1 ไม่ใช่ 2 แบบ .length */
export function visibleLength(text: string): number {
  return Array.from(text).length;
}

/**
 * ตัวเลขราคาแบบเดิม — ยังใช้กับแจ้งเตือน "สัญญาณเดี่ยว" (buildSingleSignalPayload) เท่านั้น
 *
 * ⚠ ห้ามแก้ ถ้าจะแก้ให้ไปแก้ fmtPrice แทน — มีเทสต์เทียบข้อความของสัญญาณเดี่ยวกับฉบับ
 *   ก่อนรีแฟกเตอร์ทีละตัวอักษรอยู่ (scripts/test-push-digest.mjs หัวข้อ 1)
 *   ถ้าตัวนี้เปลี่ยน เทสต์นั้นจะแดง ซึ่งแปลว่า "ของเดิมพัง" ไม่ใช่ "เทสต์ล้าสมัย"
 */
export function fmt(n: number): string {
  if (!Number.isFinite(n)) return '-';
  if (Math.abs(n) >= 1000) return n.toLocaleString('en-US', { maximumFractionDigits: 2 });
  if (Math.abs(n) >= 1) return n.toFixed(4).replace(/0+$/, '').replace(/\.$/, '');
  return n.toPrecision(4);
}

/** ตัดศูนย์ท้ายทศนิยมทิ้ง ("1.08450" → "1.0845") — ประหยัดพื้นที่บรรทัดโดยไม่เสียความหมาย */
function trimZeros(s: string): string {
  return s.includes('.') ? s.replace(/0+$/, '').replace(/\.$/, '') : s;
}

/**
 * ตัวเลขราคาของแจ้งเตือนแบบชุด — ต้องอ่านออกทั้งจักรวาลด้วยกฎเดียว
 *
 * ทำไมไม่ใช้ fmt เดิม: fmt ปัดเป็นทศนิยม 4 ตำแหน่งเมื่อค่า >= 1
 * EURUSD 1.08452 จึงกลายเป็น 1.0845 = หายไปครึ่งจุด ซึ่งเป็นตัวเลขที่เจ้าของเอาไปตั้ง SL จริง
 * สเปกรอบนี้บังคับว่าต้องอ่านออกทั้ง XAUUSD (4 หลักหน้าจุด) และ EURUSD (ทศนิยม 5 ตำแหน่ง)
 *
 * ความละเอียดจึงผูกกับ "ขนาดของราคา" ไม่ใช่ชื่อสัญลักษณ์ (จักรวาลเพิ่มตัวใหม่ได้ตลอด
 * ถ้าไปผูกกับรายชื่อ วันไหนเพิ่มเหรียญใหม่แล้วลืมแก้ตาราง ตัวเลขจะเพี้ยนเงียบ ๆ):
 *   >= 1000  → ทศนิยม 2 + คั่นหลักพัน   (2,650.25 · 95,200)
 *   >= 100   → ทศนิยม 2                (228.4)
 *   >= 10    → ทศนิยม 3                (34.85)
 *   >= 1     → ทศนิยม 5                (1.08452 · 1.261)
 *   < 1      → เลขนัยสำคัญ 5 ตัว        (0.02871 · 0.0000123)
 */
export function fmtPrice(n: number): string {
  if (!Number.isFinite(n)) return '-';
  const a = Math.abs(n);
  if (a >= 1000) return n.toLocaleString('en-US', { maximumFractionDigits: 2 });
  if (a >= 100) return trimZeros(n.toFixed(2));
  if (a >= 10) return trimZeros(n.toFixed(3));
  if (a >= 1) return trimZeros(n.toFixed(5));
  if (a === 0) return '0';
  return trimZeros(n.toPrecision(5));
}

/** ป้ายทิศทางแบบเต็ม (ใช้ในหัวข้อ) — สีบอกทิศเร็วสุด แต่ต้องมีคำไทยกำกับเผื่อคนตาบอดสี */
function directionLabel(action: Signal['action']): string {
  if (action === 'BUY') return '🟢 ซื้อ';
  if (action === 'SELL') return '🔴 ขาย';
  if (action === 'CLOSE') return '⚪ ปิด';
  return '⚪ รอ';
}

/**
 * ป้ายทิศทางแบบสั้น (ใช้ในบรรทัดรายการ) — ตัดคำไทยออกเพื่อเอาที่ไปใส่ TP/SL
 * ยังอ่านออกโดยไม่ต้องพึ่งสี เพราะรูปทรงต่างกัน (วงกลมทึบเขียว/แดง vs วงกลมขาว)
 */
function directionMark(action: Signal['action']): string {
  if (action === 'BUY') return '🟢';
  if (action === 'SELL') return '🔴';
  return '⚪';
}

