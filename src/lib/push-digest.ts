/**
 * แจ้งเตือนของสัญญาณเดี่ยว — รูปแบบเดิมทุกตัวอักษร
 *
 * ⚠ ไม่มีเส้นทางไหนในระบบใช้ตัวนี้แล้ว (DIGEST_MIN_SIGNALS = 1 แปลว่ารวมชุดเสมอ
 *   และ /api/cron/scan-markets เลิกยิงทีละสัญญาณแล้ว) ที่ยังอยู่เพราะเป็น "หลักไมล์"
 *   ให้เทียบว่าข้อความที่ผู้ใช้เห็นไม่เพี้ยนไปจากฉบับก่อนรีแฟกเตอร์
 *   (scripts/test-push-digest.mjs หัวข้อ 1 เทียบทีละตัวอักษร)
 *   จะลบทิ้งได้เมื่อไหร่ก็ต้องลบเทสต์หัวข้อนั้นพร้อมกัน
 *
 * หน้าจอล็อกของ iPhone ตัดข้อความค่อนข้างสั้น จึงเรียงของสำคัญไว้หน้าสุด:
 * ทิศทาง → สัญลักษณ์ → ราคาเข้า แล้วค่อยตามด้วย SL/TP
 */
export function buildSingleSignalPayload(signal: Signal): PushPayload {
  const strong = signal.strength === 'very_strong' || signal.strength === 'strong';

  return {
    title: `${directionLabel(signal.action)} ${signal.symbol} @ ${fmt(signal.entry_price)}`,
    body:
      `TP ${fmt(signal.take_profit)} · SL ${fmt(signal.stop_loss)}\n` +
      `ความมั่นใจ ${signal.confidence}%${strong ? ' · สัญญาณแรง' : ''} · ${signal.timeframe}`,
    // ผูก tag กับ id ของสัญญาณ ไม่ใช่แค่ symbol — สัญญาณคนละตัวของ symbol เดียวกัน
    // ต้องเด้งแยกกัน ไม่ใช่ตัวใหม่ไปทับตัวเก่าจนพลาดไปหนึ่งสัญญาณ
    tag: `signal-${signal.id}`,
    url: '/signals',
  };
}

/** บรรทัดสรุปรูปทรงของชุด — เห็นบรรทัดเดียวก็รู้ว่าตลาดกำลังเอียงไปทางไหน */
function summaryLine(signals: Signal[]): string {
  const buy = signals.filter((s) => s.action === 'BUY').length;
  const sell = signals.filter((s) => s.action === 'SELL').length;
  const other = signals.length - buy - sell;
  const strong = signals.filter((s) => s.strength === 'very_strong' || s.strength === 'strong').length;

  const parts: string[] = [];
  if (buy) parts.push(`ซื้อ ${buy}`);
  if (sell) parts.push(`ขาย ${sell}`);
  if (other) parts.push(`อื่น ${other}`);
  if (strong) parts.push(`แรง ${strong}`);
  return parts.join(' · ');
}

/**
 * บรรทัดหนึ่งรายการในชุด: "อันดับ. ทิศทาง สัญลักษณ์ ราคาเข้า TP … · SL …"
 *
 * เจ้าของสั่งว่าต้องเห็น เข้า/TP/SL จากหน้าจอล็อกแล้วตัดสินใจได้เลย — ทั้งสามตัวจึงอยู่บรรทัดเดียว
 * มีเลขอันดับนำหน้าเพราะสเปกคือ "รายการที่เรียงลำดับแล้ว" ไม่ใช่ "กองสัญญาณ"
 * ถ้าไม่ใส่เลข เจ้าของแยกไม่ออกว่าลำดับในแจ้งเตือนคือลำดับเดียวกับในเว็บหรือแค่เรียงตามเวลา
 *
 * เมื่อบรรทัดยาวเกินงบ จะ "ลดของ" ตามลำดับนี้ และห้ามตัดตัวเลขกลางตัวเด็ดขาด:
 *   1. ตัดราคาเข้าออก (เปิดแอปดูได้ แต่ TP/SL คือตัวคุมความเสี่ยง ห้ามหาย)
 *   2. ยังยาวอีก = สัญลักษณ์ยาวผิดปกติ (มาจาก watchlist ที่ผู้ใช้พิมพ์เอง) → ตัดเฉพาะชื่อ
 * ที่ยอมแลก: บรรทัดในชุดเดียวกันอาจหน้าตาไม่เท่ากัน — ยอม เพราะทางเลือกคือตัวเลขโดนตัดครึ่ง
 */
function signalLine(index: number, s: Signal, budget: number, showIndex: boolean): string {
  const mark = directionMark(s.action);
  // มีรายการเดียวไม่ต้องมีเลขอันดับ — "อันดับ 1 จาก 1" ไม่ได้บอกอะไร เปลืองที่เปล่า ๆ
  const no = showIndex ? `${index}. ` : '';
  const head = `${no}${mark} ${s.symbol}`;
  const tail = ` TP ${fmtPrice(s.take_profit)} · SL ${fmtPrice(s.stop_loss)}`;

  const full = `${head} ${fmtPrice(s.entry_price)}${tail}`;
  if (visibleLength(full) <= budget) return full;

  const noEntry = `${head}${tail}`;
  if (visibleLength(noEntry) <= budget) return noEntry;

  const room = budget - visibleLength(`${no}${mark} ${tail}`);
  return `${no}${mark} ${clip(s.symbol, Math.max(3, room))}${tail}`;
}

/**
 * tag ของชุดแจ้งเตือน — ตัดสินใจว่า "ชุดใหม่ทับชุดเก่าเมื่อไหร่"
 *
 * ทางเลือกที่ทิ้ง และเหตุผล
 *  - tag คงที่ตัวเดียว (เช่น 'signal-digest'): ทับได้เสมอ หน้าจอล็อกสะอาดสุด
 *    แต่ชุด 10:00 ที่มี 5 สัญญาณจะถูกชุด 11:00 ที่มี 1 สัญญาณทับหายไปเงียบ ๆ
 *    ถ้ายังไม่ได้ปลดล็อกดู = พลาดไป 5 ตัวโดยไม่รู้ตัว → ตัดทิ้ง
 *  - tag ไม่ซ้ำเลยต่อชุด: ไม่พลาดอะไรเลย แต่ค้างสะสมเต็มหน้าจอล็อก
 *    ซึ่งเป็นปัญหาเดียวกับที่ digest ตั้งใจแก้ตั้งแต่แรก → ตัดทิ้ง
 *
 * ที่เลือก: ผูก tag กับ "ช่องเวลา" ที่กว้างเท่าคาบของตัวสแกน (60 นาที)
 *  - ตัวสแกนรอบ 10:00 กับรอบ 11:00 อยู่คนละช่อง → ไม่ทับกัน ไม่มีทางพลาดสัญญาณ
 *  - กดสั่งรันเองซ้ำ ๆ ในชั่วโมงเดียวกันอยู่ช่องเดียวกัน → ทับกันเอง ไม่ค้างเป็นตับ
 *  - ช่องเดียวกันนี้ยังเป็นหน่วยเดียวกับที่ roundThrottleVerdict ใช้ตัดสินว่า
 *    "ชั่วโมงนี้แจ้งไปแล้วหรือยัง" — สองอย่างจึงเถียงกันเองไม่ได้
 */
export function digestTag(nowMs: number): string {
  const windowMs = PUSH_DIGEST_CONFIG.TAG_WINDOW_MINUTES * 60_000;
  return `signal-digest-${Math.floor(nowMs / windowMs)}`;
}

/**
 * แจ้งเตือนแบบชุด — ต้องตัดสินใจได้จากหน้าจอล็อกโดยไม่ต้องปลดล็อก
 *
 * โครง:
 *   หัวข้อ : 🟢 ซื้อ XAUUSD 2,650.25 · อีก 6
 *   เนื้อ  : 1. 🟢 XAUUSD 2,650.25 TP 2,690.25 · SL 2,640.25
 *            2. 🔴 EURUSD 1.08452 TP 1.07252 · SL 1.09052
 *            …
 *            + อีก 3 ตัว · ซื้อ 4 · ขาย 3 · แรง 3
 *
 * ทำไมหัวข้อไม่มี TP/SL: งบหัวข้อ 40 ตัวอักษรใส่ไม่พอ และตัวที่คนเห็นแน่ ๆ ตอนไม่กาง
 * คือหัวข้อ + เนื้อความบรรทัดแรก — บรรทัดแรกจึงเป็นอันดับ 1 แบบเต็ม (มี TP/SL ครบ)
 * ยอมให้ชื่อ/ราคาของอันดับ 1 ซ้ำกับหัวข้อ เพราะการมี TP/SL ให้เห็นสำคัญกว่าความสวย
 *
 * ทำไมบรรทัดสรุป (ซื้อกี่ตัว/ขายกี่ตัว) ไปอยู่ท้าย: มันบอก "รูปทรงตลาด" ซึ่งดีแต่ไม่ใช่
 * สิ่งที่เอาไปตั้งออเดอร์ได้ ถ้าวางไว้บรรทัดแรกแบบเดิม มันจะไปเบียดสัญญาณอันดับ 1
 * ตกไปอยู่บรรทัดที่คนไม่เห็นตอนแบนเนอร์ยังไม่กาง
 */
export function buildDigestPayload(signals: Signal[], nowMs: number, scorer?: SpeedScorer | null): PushPayload {
  const list = collapseDuplicates(rankSignals(signals, scorer));
  const [top, ...rest] = list;

  // จำนวนที่เหลือห้ามโดนตัดทิ้งจากการ clip — ตัดชื่อ/ราคาก่อน แล้วค่อยต่อท้ายทีหลัง
  const suffix = rest.length > 0 ? ` · อีก ${rest.length}` : '';
  const head = `${directionLabel(top.action)} ${top.symbol} ${fmtPrice(top.entry_price)}`;
  const title =
    clip(head, Math.max(8, PUSH_DIGEST_CONFIG.TITLE_MAX_CHARS - visibleLength(suffix))) + suffix;

  const budget = PUSH_DIGEST_CONFIG.BODY_LINE_MAX_CHARS;
  const shown = list.slice(0, PUSH_DIGEST_CONFIG.DIGEST_MAX_ITEMS);
  const lines = shown.map((s, i) => signalLine(i + 1, s, budget, list.length > 1));

  const hidden = list.length - shown.length;
  // "ตัดทิ้งเงียบ" คือสิ่งที่ห้ามที่สุด — ถ้าโชว์ไม่หมดต้องบอกจำนวนเสมอ
  if (hidden > 0) lines.push(clip(`+ อีก ${hidden} ตัว · ${summaryLine(list)}`, budget));

  return {
    title,
    body: lines.join('\n'),
    tag: digestTag(nowMs),
    url: '/signals',
  };
}

/**
 * ตัวตัดสินหลัก: รับสัญญาณของผู้ใช้หนึ่งคนในรอบหนึ่ง → คืนแจ้งเตือนที่ควรยิงจริง
 *
 * คืนอาเรย์ (ไม่ใช่ตัวเดียว) เพื่อให้ผู้เรียกไม่ต้องแยกเคส — ในทางปฏิบัติยาว 0 หรือ 1 เสมอ
 * ไม่มีเส้นทางไหนที่คืนมากกว่า 1 เพราะนั่นคือการสั่นซ้ำที่ไฟล์นี้มีไว้เพื่อกำจัด
 */
export function buildPushPayloads(signals: Signal[], nowMs: number, scorer?: SpeedScorer | null): PushPayload[] {
  const list = collapseDuplicates(rankSignals(signals, scorer));
  if (list.length === 0) return [];
  if (list.length < PUSH_DIGEST_CONFIG.DIGEST_MIN_SIGNALS) return [buildSingleSignalPayload(list[0])];
  return [buildDigestPayload(list, nowMs, scorer)];
}

