/**
 * แปลงคอลัมน์ indicators เป็นแถวพร้อมแสดง — คืนครบทุกคีย์เสมอ
 *
 * คืนแถวของคีย์ที่หายด้วย (value = null) โดยตั้งใจ: การซ่อนคีย์ที่หายไปทำให้ตารางของ
 * แต่ละใบมีจำนวนแถวไม่เท่ากัน แล้วผู้ใช้จะไม่มีทางรู้ว่า "ไม่มีค่า" กับ "ไม่มีช่องนี้ในระบบ"
 * ต่างกันอย่างไร — ซึ่งเป็นข้อมูลที่เขาต้องใช้ตรวจสอบเครื่องยนต์
 */
export function readSignalSnapshot(indicators: unknown): SnapshotRow[] {
  const src: Record<string, unknown> =
    indicators && typeof indicators === 'object' && !Array.isArray(indicators)
      ? (indicators as Record<string, unknown>)
      : {};

  return SNAPSHOT_KEYS.map((spec) => {
    const raw = src[spec.key];
    // ยอมรับตัวเลขที่มาเป็นสตริงด้วย เพราะไดรเวอร์ของ numeric/jsonb บางตัวคืนสตริง
    const num =
      typeof raw === 'number' ? raw : typeof raw === 'string' && raw.trim() !== '' ? Number(raw) : NaN;
    const ok = Number.isFinite(num);
    return {
      key: spec.key,
      label: spec.label,
      value: ok ? num : null,
      text: ok ? num.toFixed(spec.decimals) : '—',
      missingNote: ok ? null : spec.missingNote,
      // footnote ติดมากับคีย์ ไม่ได้ขึ้นกับว่ามีค่าไหม — แต่ไม่ต้องอธิบายค่าที่ไม่มี
      footnote: ok ? spec.footnote ?? null : null,
    };
  });
}

/** true = ใบนี้ไม่มีตัวเลขที่ใช้ได้เลยสักคีย์ (แถวเก่ามาก / แถวที่ indicators เป็น {}) */
export function snapshotIsEmpty(rows: readonly SnapshotRow[]): boolean {
  return rows.every((r) => r.value === null);
}

/** หนึ่งเหตุผลที่เครื่องยนต์ให้ไว้ตอนออกใบนั้น */
export interface SnapshotReason {
  type: string;
  label: string;
  detail: string;
}

/**
 * แปลงคอลัมน์ reasons เป็นรายการพร้อมแสดง
 *
 * ทนกับรูปที่ไม่ตรง: ไม่ใช่อาร์เรย์ → ว่าง · สมาชิกที่ไม่มี label → ข้าม
 * ห้ามแปลข้อความหรือแต่งเติมอะไรทั้งสิ้น — นี่คือคำที่เครื่องยนต์เขียนไว้เอง
 * การเปลี่ยนถ้อยคำตรงนี้เท่ากับปลอมบันทึกของระบบ
 *
 * ⚠ มีกฎหนึ่งข้อที่ให้คะแนนแล้ว **ไม่ push reason เลย** คือโมเมนตัมของ MACD histogram
 *   (signal-engine.ts:172-178 ±1) รายการนี้จึงไม่ใช่รายการคะแนนทั้งหมดที่ใบนั้นได้
 *   UI ที่แสดงรายการนี้ต้องไม่เขียนว่า "นี่คือเหตุผลทั้งหมด"
 */
export function readSignalReasons(reasons: unknown): SnapshotReason[] {
  if (!Array.isArray(reasons)) return [];
  const out: SnapshotReason[] = [];
  for (const r of reasons) {
    if (!r || typeof r !== 'object' || Array.isArray(r)) continue;
    const o = r as Record<string, unknown>;
    const label = typeof o.label === 'string' ? o.label.trim() : '';
    if (!label) continue;
    out.push({
      type: typeof o.type === 'string' ? o.type : 'unknown',
      label,
      detail: typeof o.detail === 'string' ? o.detail : '',
    });
  }
  return out;
}
