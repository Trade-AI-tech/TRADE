/** หนึ่งแถวในตาราง "เครื่องยนต์เห็นอะไรตอนนั้น" */
export interface SnapshotRow {
  /** คีย์จริงในคอลัมน์ signals.indicators */
  key: string;
  /** ป้ายที่ผู้ใช้เห็น — ต้องบอกชนิดและคาบให้ตรงกับของจริง */
  label: string;
  /** ค่าที่บันทึกไว้ · null = ใบนี้ไม่มีคีย์นั้น */
  value: number | null;
  /** ข้อความพร้อมแสดง — ทศนิยมเท่ากับที่เครื่องยนต์บันทึกลง DB จริง */
  text: string;
  /** ทำไมถึงไม่มีค่านั้น (แสดงเป็นคำอธิบายเล็ก ๆ) · null = มีค่าปกติ */
  missingNote: string | null;
  /**
   * คำอธิบายที่ต้องแสดงแม้ **ค่ามีอยู่ครบ** — ใช้กับคีย์ที่ตัวเลขในนั้นอาจไม่ใช่สิ่งที่
   * ชื่อคีย์บอก (ตอนนี้มีตัวเดียวคือ atr) · null = ป้ายบอกครบแล้ว ไม่ต้องอธิบายอะไรอีก
   * UI ต้องแสดงข้อความนี้ให้เห็นจริง ไม่ใช่ซ่อนไว้ใน tooltip เพราะบนมือถือไม่มี hover
   */
  footnote: string | null;
}

