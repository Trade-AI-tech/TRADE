-- ============================================
-- 006 — สถานะ "แจ้งเตือนแล้วหรือยัง" ของแต่ละสัญญาณ (idempotent, non-destructive)
--
-- วางทั้งไฟล์ลง Supabase → SQL Editor → Run ครั้งเดียวจบ · รันซ้ำกี่รอบก็ปลอดภัย
-- ⚠ ห้ามใส่ DROP TABLE ของตารางฝั่งเทรดลงในไฟล์นี้เด็ดขาด (กติกาเดิมของ repo)
--
-- ── บั๊กที่ไฟล์นี้มาแก้ ────────────────────────────────────────────────────────────
-- เดิมตัวสแกนทำสองอย่างตามลำดับนี้: เขียนแถวลง signals ก่อน → แล้วค่อยเรียกตัวส่งแจ้งเตือน
-- ถ้าตัวจำกัดความถี่บอกว่า "เพิ่งส่งไป ยังไม่ถึงเวลา" รอบนั้นจะไม่ส่ง
-- รอบถัดไปตัวกันสัญญาณซ้ำเห็นแถวเดิมอยู่ใน signals แล้ว (1D กัน 20 ชม. / 1H กัน 4 ชม.)
-- จึงข้ามไปไม่สร้างใหม่ → สัญญาณนั้นไม่มีวันได้แจ้งเตือนอีกเลย และไม่มีคอลัมน์ไหน
-- บอกได้ว่า "แถวนี้ยังไม่เคยแจ้ง" = ตรวจไม่พบ กู้คืนไม่ได้ ขัดคำสั่งเจ้าของที่ว่า
-- ให้แจ้งเตือนมาทุกกราฟที่มีสัญญาณ
--
-- ตั้งแต่มีสองคอลัมน์นี้ ตัวส่งจะเลือก "สัญญาณที่ยัง active และยังไม่เคยแจ้งเตือน" ทั้งหมด
-- ไม่ใช่แค่ของรอบนี้ → รอบไหนส่งไม่สำเร็จหรือถูกกันไว้ รอบหน้าเก็บตกได้เอง
-- ============================================

-- 0. ตารางที่จะแก้ต้องมีอยู่จริงก่อน — ไม่งั้น error ของ Postgres จะอ่านไม่รู้เรื่อง
--    ว่าต้องไปรัน 002_trading_schema.sql ก่อน
do $$
begin
  if to_regclass('public.signals') is null then
    raise exception 'ยังไม่มีตาราง signals — ให้รัน supabase/migrations/002_trading_schema.sql ก่อนแล้วค่อยรันไฟล์นี้';
  end if;
end $$;

-- ============================================
-- 1. คอลัมน์สถานะการแจ้งเตือน
-- ============================================
--
-- ⚠ ค่าเริ่มต้นเป็น true ไม่ใช่ false — ตั้งใจ และเป็นหัวใจของความถูกต้องทั้งไฟล์
--
--   ตาราง signals มีตัวเขียนอยู่หลายตัว และแต่ละตัวแจ้งเตือนของตัวเองตอน insert อยู่แล้ว:
--     · supabase/functions/scan-signals   (pg_cron ยิงนาทีที่ 0 ทุกชั่วโมง — ส่ง push เอง)
--     · src/app/api/cron/scan-markets     (cron ของ Vercel — ส่ง push เอง ทีละสัญญาณ)
--     · scripts/scan-universe.mjs         (GitHub Actions นาทีที่ 25 — ตัวเดียวที่รู้จักคอลัมน์นี้)
--   ถ้าตั้งค่าเริ่มต้นเป็น false แถวที่สองตัวแรกเขียน (และแจ้งเตือนไปแล้ว) จะกลายเป็น
--   "ยังไม่เคยแจ้ง" ในสายตาตัวสแกนจักรวาล แล้วโดนกวาดมาแจ้งซ้ำอีกใบในชั่วโมงเดียวกัน
--   = เจ้าของเห็นสัญญาณเดียวกันสองครั้ง ซึ่งขัดสเปก "ชั่วโมงละ 1 ครั้ง" พอ ๆ กับบั๊กเดิม
--
--   ค่าเริ่มต้น true จึงแปลว่า "ใครไม่ระบุ แปลว่าตัวเองแจ้งเองแล้ว"
--   ส่วนตัวสแกนจักรวาลระบุ push_sent = false มาเองทุกแถว (มันเป็นตัวเดียวที่ให้ตัวส่งกลางแจ้งให้)
--
--   ผลพลอยได้: แถวเก่าทั้งหมดที่มีอยู่ก่อนรันไฟล์นี้ได้ค่า true ทันที จึงไม่มี
--   "แจ้งเตือนย้อนหลังทีเดียว 50 ใบ" ตอนรอบสแกนแรกหลังรัน migration — ไม่ต้องมี backfill
alter table signals add column if not exists push_sent boolean not null default true;

-- เวลาที่แจ้งเตือนออกไปสำเร็จ — ใช้เป็น "นาฬิกาเฉพาะของแจ้งเตือนสัญญาณ"
-- (แยกจาก push_subscriptions.last_used_at ที่ขยับตามปุ่มทดสอบด้วย ซึ่งทำให้
--  การกดปุ่มทดสอบไปกันแจ้งเตือนจริงของชั่วโมงนั้นทิ้ง)
alter table signals add column if not exists push_sent_at timestamptz;

comment on column signals.push_sent is
  'แจ้งเตือน push ของแถวนี้ออกไปแล้วหรือยัง · ค่าเริ่มต้น true = ผู้เขียนแถวแจ้งเองแล้ว · ตัวสแกนจักรวาลเขียน false เพื่อให้ตัวส่งกลางแจ้งให้';
comment on column signals.push_sent_at is
  'เวลาที่แจ้งเตือน push ออกไปสำเร็จ · null = ยังไม่เคยแจ้ง · ใช้เป็นนาฬิกาของกติกา "ชั่วโมงละ 1 ครั้ง"';

-- ============================================
-- 2. ดัชนี
-- ============================================
--
-- ดัชนีบางส่วน (partial) เพราะคำค้นที่ใช้จริงมีเงื่อนไขคงที่ติดมาด้วยเสมอ
-- แถวที่แจ้งแล้ว (ส่วนใหญ่ของตาราง) จึงไม่ต้องอยู่ในดัชนีให้เปลืองที่และเปลืองเวลาเขียน

-- ใช้โดย loadPendingSignals: หาของค้างของผู้ใช้คนหนึ่ง เรียงตามเวลาสร้าง
create index if not exists idx_signals_push_pending
  on signals (user_id, created_at desc)
  where status = 'active' and push_sent = false;

-- ใช้โดยตัวเช็ก "ชั่วโมงนี้แจ้งไปหรือยัง": หาเวลาแจ้งล่าสุดของผู้ใช้คนหนึ่ง
create index if not exists idx_signals_push_sent_at
  on signals (user_id, push_sent_at desc)
  where push_sent_at is not null;

-- ============================================
-- 3. ตรวจผล — ควรเห็นครบทั้ง 3 บล็อกนี้หลังรันเสร็จ
-- ============================================

-- 3.1 คอลัมน์ถูกเพิ่มจริงไหม (ต้องได้ 2 แถว · push_sent ต้องเป็น not null default true)
select
  column_name   as "คอลัมน์",
  data_type     as "ชนิด",
  is_nullable   as "ว่างได้ไหม",
  column_default as "ค่าเริ่มต้น"
from information_schema.columns
where table_schema = 'public'
  and table_name = 'signals'
  and column_name in ('push_sent', 'push_sent_at')
order by column_name;

-- 3.2 ดัชนีถูกสร้างจริงไหม (ต้องได้ 2 แถว)
select indexname as "ชื่อดัชนี", indexdef as "นิยาม"
from pg_indexes
where schemaname = 'public'
  and tablename = 'signals'
  and indexname in ('idx_signals_push_pending', 'idx_signals_push_sent_at')
order by indexname;

-- 3.3 ตอนนี้มีสัญญาณค้างรอแจ้งอยู่กี่ตัว
--     รันครั้งแรกควรได้ 0 (แถวเก่าทั้งหมดได้ค่าเริ่มต้น true = ถือว่าแจ้งแล้ว)
--     หลังตัวสแกนรอบถัดไปทำงาน ค่านี้จะขึ้นชั่วคราวแล้วกลับเป็น 0 เมื่อแจ้งเตือนออกสำเร็จ
select
  count(*) filter (where push_sent = false and status = 'active') as "ค้างรอแจ้ง",
  count(*) filter (where push_sent_at is not null)                as "เคยแจ้งผ่านตัวส่งกลาง",
  count(*)                                                        as "ทั้งหมด"
from signals;
