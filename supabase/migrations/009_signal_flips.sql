-- ============================================
-- 009 — ป้าย "สัญญาณใบนี้โดนกลับทิศแล้ว" (idempotent, non-destructive)
--
-- วางทั้งไฟล์ลง Supabase → SQL Editor → Run ครั้งเดียวจบ · รันซ้ำกี่รอบก็ปลอดภัย
-- ⚠ ห้ามใส่ DROP TABLE ของตารางฝั่งเทรดลงในไฟล์นี้เด็ดขาด (กติกาเดิมของ repo)
--
-- ── ช่องโหว่ที่ไฟล์นี้มาปิด ────────────────────────────────────────────────────────
-- ตัวกันซ้ำของตัวสแกนใช้คีย์ user+symbol+action+timeframe — action อยู่ในคีย์
-- แปลว่าสัญญาณ "ทิศตรงข้าม" ของกราฟเดิมไม่ถูกกันซ้ำ มันถูกบันทึกเป็นใบใหม่ตามปกติ
-- สิ่งที่หายไปคือ "การเชื่อมโยง": ไม่มีอะไรบอกเจ้าของเลยว่าใบ BUY เดิมที่ยังเปิดอยู่
-- เพิ่งโดนเครื่องยนต์อ่านกลับทิศเป็น SELL — เจ้าของที่ถือไม้ตามใบเดิมจะไม่รู้ตัว
-- จนกว่าจะไปไล่ดูเอง (เจ้าของสั่งเมื่อ 2026-08-28 ให้บอกชัด ๆ เพื่อพิจารณาปิดไม้เอง)
--
-- สองคอลัมน์นี้คือ "ป้าย" บนใบเก่า เขียนโดย scripts/scan-universe.mjs หลัง insert
-- ใบทิศตรงข้ามสำเร็จ แล้วหน้าเว็บ (SignalCard) อ่านไปขึ้นแถบเตือน
--
-- ── กติกาที่ต้องไม่เปลี่ยน (flipped ≠ closed) ─────────────────────────────────────
--  · การปั๊มป้ายนี้ **ไม่ปิดบัญชีใบเก่า** — เราไม่รู้ว่าเจ้าของปิดไม้จริงหรือเปล่า
--    ตัวเก็บผล (scripts/resolve-signals.mjs) ยังต้อง resolve ใบที่โดนปั๊มตามปกติทุกอย่าง
--    เพื่อให้ ledger บันทึก "สิ่งที่สัญญาณทำ" ต่อไป ไม่ใช่ "สิ่งที่เจ้าของอาจจะทำ"
--  · ห้ามให้ป้ายนี้ไปแตะ status/outcome — สองแกนนั้นเป็นของตัวสแกน/ตัวเก็บผลตามเดิม
--  · ความหน่วงของการตรวจจับ = รอบสแกนของ GitHub Actions (~15-56 นาที) ไม่ใช่เรียลไทม์
--
-- ── ทำไมไม่มี index / ไม่มี FK ────────────────────────────────────────────────────
--  · ไม่มี query ฝั่งเซิร์ฟเวอร์ตัวไหนกรองด้วยสองคอลัมน์นี้เลย — ตัวสแกนหาใบที่จะปั๊ม
--    ผ่าน query กันซ้ำเดิม (status='active' + created_at ซึ่งมี index อยู่แล้วจาก 002)
--    แล้วกรอง flipped_at ในหน่วยความจำ ส่วนหน้าเว็บโหลดแถวของผู้ใช้มาทั้งชุดอยู่แล้ว
--    index ที่ไม่มีใครใช้มีแต่ต้นทุนตอนเขียน จึงตั้งใจไม่สร้าง
--  · flipped_by เป็น soft reference (ไม่มี FK) — มันคือป้ายอธิบาย ไม่ใช่ความสัมพันธ์
--    ที่ต้องบังคับ ถ้าใส่ FK แล้ววันหนึ่งมีงานล้างแถวเก่า จะลบไม่ได้เพราะโดนใบอื่นอ้างอยู่
-- ============================================

-- 0. ตารางที่จะแก้ต้องมีอยู่จริงก่อน
do $$
begin
  if to_regclass('public.signals') is null then
    raise exception 'ยังไม่มีตาราง signals — ให้รัน supabase/migrations/002_trading_schema.sql ก่อนแล้วค่อยรันไฟล์นี้';
  end if;
end $$;

-- ============================================
-- 1. คอลัมน์ป้ายกลับทิศ
-- ============================================
alter table public.signals add column if not exists flipped_at timestamptz;
alter table public.signals add column if not exists flipped_by uuid;

comment on column public.signals.flipped_at is
  'เวลาที่เครื่องยนต์ออกสัญญาณทิศตรงข้ามบน symbol+timeframe เดียวกันขณะใบนี้ยังเปิดอยู่ · null = ยังไม่เคยโดนกลับทิศ · ป้ายนี้ไม่ปิดบัญชี — ตัวเก็บผลยัง resolve ใบนี้ตามปกติ (flipped ≠ closed)';
comment on column public.signals.flipped_by is
  'id ของใบทิศตรงข้ามที่มากลับทิศใบนี้ (soft reference ไปที่ signals.id ใบใหม่ — ไม่มี FK โดยตั้งใจ ดูหัวไฟล์)';
